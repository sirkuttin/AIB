// Builds AIB's two local-docs vendor bundles (run once after npm install; the outputs are committed, the app has no build step):
//   outputs/agent-studio/server/docs/vendor/yjs.js   Yjs + y-protocols for the Deno server (ESM, types in yjs.d.ts)
//   outputs/agent-studio/vendor/docs/editor.js       TipTap + y-prosemirror + Yjs editor for the page (IIFE, window.AIBDocEditor)
import { build } from 'esbuild';
import { statSync } from 'node:fs';

const app = '../../outputs/agent-studio';
const server = `${app}/server/docs/vendor/yjs.js`;
const page = `${app}/vendor/docs/editor.js`;
await build({
  entryPoints: ['server.entry.js'], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', outfile: server, minify: true,
  banner: { js: '// deno-lint-ignore-file\n// @ts-self-types="./yjs.d.ts"\n// Generated by tools/docs-vendor/build.mjs: yjs, y-protocols, lib0 (MIT). Do not edit.' },
  legalComments: 'none',
});
await build({
  entryPoints: ['editor.entry.js'], bundle: true, format: 'iife', platform: 'browser', target: 'es2022', outfile: page, minify: true,
  banner: { js: '// Generated by tools/docs-vendor/build.mjs: TipTap, ProseMirror, y-prosemirror, yjs, y-protocols, lib0 (MIT). Do not edit.' },
  legalComments: 'none',
});
for (const f of [server, page]) console.log(f, statSync(f).size, 'bytes');
