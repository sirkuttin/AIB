// Builds the file tab's code editor (run once after npm install; the output is committed, the app has no build step):
//   app/vendor/code/editor.js   CodeMirror 6 + AIB's language set, as an IIFE (window.AIBCodeEditor)
// The page loads it lazily, on the first file tab that needs it (never in chat.html's head). Same build style as
// tools/docs-vendor/build.mjs. `node build.mjs --sizes` also prints the biggest inputs (minified bytes per package).
import { build } from 'esbuild';
import { statSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { readFileSync } from 'node:fs';

const page = '../../app/vendor/code/editor.js';
const result = await build({
  entryPoints: ['editor.entry.js'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  outfile: page,
  minify: true,
  metafile: true,
  banner: { js: '// Generated by tools/code-vendor/build.mjs: CodeMirror 6, Lezer grammars, legacy modes (MIT). Do not edit.' },
  legalComments: 'none',
});
const size = statSync(page).size;
console.log(page, size, 'bytes,', gzipSync(readFileSync(page)).length, 'gzip');
if (process.argv.includes('--sizes')) {
  const per = {};
  for (const [file, info] of Object.entries(result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].inputs)) {
    const m = file.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
    const k = m ? m[1] : file;
    per[k] = (per[k] || 0) + info.bytesInOutput;
  }
  for (const [k, v] of Object.entries(per).sort((a, b) => b[1] - a[1])) console.log(String(v).padStart(8), k);
}
