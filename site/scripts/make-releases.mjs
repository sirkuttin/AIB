// Builds src/content/docs/releases.mdx from the GitHub releases, newest first.
// Usage (from site/): node scripts/make-releases.mjs
// Needs the `gh` CLI, signed in. Pre-releases and drafts (test builds) are skipped.
// Betas 1-9 are frozen in scripts/releases-archive-beta1-9.mdx (they carry pictures); newer releases are read from GitHub.
// Each release keeps its GitHub text, minus the title and the licence line; headings move down one level.
// MDX-special characters outside code are escaped.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'sirkuttin/AIB';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gh = (...args) => execFileSync('gh', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

// The site carries exactly three puns (owner, 2026-11-12); this one stays on GitHub only.
const DROP = [' Four score and seven installers ago, we would have tested them all.'];

function escapeLine(line) {
  return line
    .split(/(`[^`]*`)/)
    .map((p, i) => (i % 2 === 0 ? p.replaceAll('<', '&lt;').replaceAll('{', '&#123;').replaceAll('}', '&#125;') : p))
    .join('');
}

function body(raw) {
  let text = raw.replaceAll('\r\n', '\n');
  for (const d of DROP) text = text.replaceAll(d, '');
  const out = [];
  let skipLicense = false;
  let inCode = false;
  for (const line of text.split('\n')) {
    if (line.startsWith('<!--') || line.startsWith('# ') || line.startsWith('*(say')) continue;
    if (line.trim() === '## License') { skipLicense = true; continue; }
    if (skipLicense) {
      if (line.startsWith('#')) skipLicense = false; else continue;
    }
    if (line.startsWith('```')) { inCode = !inCode; out.push(line); continue; }
    if (inCode) { out.push(line); continue; }
    const m = line.match(/^(#{2,5}) (.*)$/);
    out.push(m ? `#${m[1]} ${escapeLine(m[2])}` : escapeLine(line));
  }
  return out.join('\n').trim();
}

const list = JSON.parse(gh('release', 'list', '--repo', REPO, '--limit', '200', '--json', 'tagName,isPrerelease,isDraft,publishedAt'));
const tags = list
  .filter((r) => !r.isPrerelease && !r.isDraft)
  .sort((a, b) => b.publishedAt.localeCompare(a.publishedAt))
  .map((r) => r.tagName)
  .filter((t) => !/^v0\.1\.0-beta\.[1-9]$/.test(t)); // frozen in the archive

const head = `---
title: Release notes
description: Every AIB release, newest first. The same text as the GitHub releases.
tableOfContents:
  maxHeadingLevel: 2
---

{/* Generated by scripts/make-releases.mjs from the GitHub releases. Run \`node scripts/make-releases.mjs\` again to update. */}

import Shot from '../../components/Shot.astro';

Every release, newest first. Each one links to its GitHub release, where the downloads and \`SHA256SUMS\` are.
`;

const parts = [head];
for (const tag of tags) {
  const rel = JSON.parse(gh('release', 'view', tag, '--repo', REPO, '--json', 'body'));
  const version = tag.replace(/^v/, '');
  parts.push(`## ${version}\n\n[Downloads on GitHub](https://github.com/${REPO}/releases/tag/${tag})\n\n${body(rel.body)}\n`);
}
parts.push(readFileSync(join(root, 'scripts', 'releases-archive-beta1-9.mdx'), 'utf8'));
writeFileSync(join(root, 'src/content/docs/releases.mdx'), parts.join('\n'), 'utf8');
console.log(`wrote releases.mdx: ${tags.length} from GitHub + 9 archived`);
