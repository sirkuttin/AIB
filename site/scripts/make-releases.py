# The site carries exactly three puns (owner, 2026-11-12); this one from the beta.7 notes stays on GitHub only.
DROP = [' Four score and seven installers ago, we would have tested them all.']


def escape(line: str) -> str:
    parts = re.split(r'(`[^`]*`)', line)
    out = []
    for i, p in enumerate(parts):
        if i % 2 == 0:
            p = p.replace('<', '&lt;').replace('{', '&#123;').replace('}', '&#125;')
        out.append(p)
    return ''.join(out)


def body(n: int) -> str:
    text = files[n].read_text(encoding='utf-8')
    for d in DROP:
        text = text.replace(d, '')
    lines = text.splitlines()
    out = []
    skip_license = False
    in_code = False
    for line in lines:
        if line.startswith('<!--'):
            continue
        if line.startswith('# '):
            continue
        if line.startswith('*(say'):
            continue
        if line.strip() == '## License':
            skip_license = True
            continue
        if skip_license:
            if line.startswith('#'):
                skip_license = False
            else:
                continue
        if line.startswith('```'):
            in_code = not in_code
            out.append(line)
            continue
        if in_code:
            out.append(line)
            continue
        m = re.match(r'^(#{2,5}) (.*)$', line)
        if m:
            out.append('#' + m.group(1) + ' ' + escape(m.group(2)))
            for (b, head), (name, alt, phone) in SHOTS.items():
                if b == n and m.group(2).startswith(head):
                    out.append('')
                    out.append(f'<Shot name="{name}" alt="{alt}"{" phone" if phone else ""} />')
            continue
        out.append(escape(line))
    return '\n'.join(out).strip()


