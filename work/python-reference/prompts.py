"""Which saved user events are prompts (something the user said), and a search over them: the Prompts view's find box.

is_prompt() is the Python twin of ChatViews.isPrompt in views.js (which uses StreamUI.classifyUser and stripViewContext in
stream-ui.js). The two must agree: work/prompt_fixtures.json holds the shared cases and both test suites run them.
Patterns are written the way the JavaScript ones are: ASCII word boundaries, JavaScript's whitespace set, and \\Z for $
(Python's $ also matches before a final newline; JavaScript's does not).
"""
import re

# What JavaScript's \s and String.trim() treat as whitespace (Python's \s differs at \x1c-\x1f, \x85 and ﻿).
_WS = ' \t\n\x0b\x0c\r   -     　﻿'
_S = '[' + _WS + ']'
_FLAGS = re.IGNORECASE | re.ASCII


def _re(pattern):
    return re.compile(pattern.replace('[\\s\\S]', '(?s:.)').replace('\\s', _S), _FLAGS)


VIEW_CONTEXT_TEST = _re(r'<artifact-view-context\b')
VIEW_CONTEXT = _re(r'\s*<artifact-view-context\b[^>]*>[\s\S]*?</artifact-view-context\s*>\s*')
AGENT_MESSAGE = _re(r'^(?:Another Claude session sent a message:\s*)?<agent-message\b([^>]*)>([\s\S]*?)</agent-message>\s*([\s\S]*)\Z')
TEAMMATE = _re(r'^<teammate-message\b([^>]*)>([\s\S]*?)</teammate-message>\Z')
HANDBACK = _re(r'^\s*\[Subagent hand-back\]')
REPORT_FOLLOWS = _re(r'The report follows:')
TRAILER = _re(r'^That\s+[“"\']?other Claude session')
TASK_NOTE = _re(r'<task-notification\b[^>]*>[\s\S]*?</task-notification>')
TASK_NOTE_START = _re(r'^<task-notification\b')
# Wrapper blocks the agent's harness injects into a user turn: the same list and peeling as StreamUI (stream-ui.js).
INJECTED_TAGS = ('system-reminder|side-sessions-event|user-prompt-submit-hook|hook-output|session-start-hook|'
                 'post-tool-use-hook|pre-tool-use-hook|stop-hook|ide_opened_file|ide_selection|ide_diagnostics|'
                 'environment_details|system_instruction|cross-session-message')
INJECTED_START = _re(r'^<(?:' + INJECTED_TAGS + r')(?![\w-])')
_BLOCK = r'<(' + INJECTED_TAGS + r')(?![\w-])[^>]*>((?:(?!</\1\s*>)[\s\S])*)</\1\s*>'
INJECTED_LEAD = _re(r'^\s*' + _BLOCK)
INJECTED_TAIL = _re(_BLOCK + r'\s*\Z')
ANY_TAG = _re(r'<[a-z]')
BOILERPLATE = _re(r'^\s*(?:this session is being continued from a previous conversation|'
                  r'caveat:\s*the messages below were generated by the user while running local commands|'
                  r'\[request interrupted by user|base directory for this skill:|the user opened the file|'
                  r'<local-command-|continue from where you left off)')
MAX_CLASSIFIED = 500000   # classifyUser ignores longer text (it is then a prompt, as in the page)
SHOWN = 300               # characters of a prompt the search returns


def _strip(text):
    return text.strip(_WS)


def strip_view_context(text):
    if not isinstance(text, str) or not VIEW_CONTEXT_TEST.search(text):
        return text
    return _strip(VIEW_CONTEXT.sub(' ', text))


def _peel_injected(text):
    """Leading and trailing injected blocks off text: (the stripped rest, how many blocks came off)."""
    s, count = text, 0
    while True:
        m = INJECTED_LEAD.match(s)
        if not m:
            break
        s, count = s[m.end():], count + 1
    while True:
        m = INJECTED_TAIL.search(s)
        if not m:
            break
        s, count = s[:m.start()], count + 1
    return _strip(s), count


def strip_injected(text):
    """StreamUI.stripInjected: the person's words of a turn, injected blocks at either end dropped ('' when nothing else is left)."""
    if not ANY_TAG.search(text) or len(_strip(text)) > MAX_CLASSIFIED:   # longer text is left whole, as is_wrapper leaves it
        return text
    rest, count = _peel_injected(text)
    return rest if count else text


def is_wrapper(text):
    """StreamUI.classifyUser(text) !== null: the whole text is an injected note (agent message, hand-back, task notice, reminder)."""
    s = _strip(text)
    if not s or len(s) > MAX_CLASSIFIED:
        return False
    m = AGENT_MESSAGE.match(s)
    if m:
        rest = _strip(m.group(3))
        if not rest or TRAILER.search(rest):
            return True
    if TEAMMATE.match(s):
        return True
    if HANDBACK.search(s) and REPORT_FOLLOWS.search(s):
        return True
    if not _strip(TASK_NOTE.sub('', s)) and TASK_NOTE_START.search(s):
        return True
    if INJECTED_START.search(s):
        rest, count = _peel_injected(s)
        if count and not rest:
            return True
    return False


def has_files(event):
    images = event.get('images')
    if not isinstance(images, list):
        return False
    return any(isinstance(im, dict) and type(im.get('n')) is int and type(im.get('i')) is int for im in images)


def prompt_text(event):
    value = event.get('text')
    return strip_injected(strip_view_context(value)) if isinstance(value, str) else ''


def is_prompt(event):
    """A saved user event that is something the user said: not an injected note, boilerplate or an interrupt."""
    if not isinstance(event, dict) or event.get('kind') != 'user':
        return False
    if has_files(event):
        return True
    text = prompt_text(event)
    if not text or not _strip(text):
        return False
    if is_wrapper(text):
        return False
    return not BOILERPLATE.search(text)


def find_prompts(events, query='', limit=200):
    """The user's prompts in `events` (the same list /api/transcript pages through, so `index` is the real event index) whose text
    contains `query` (case-insensitive). Newest `limit` kept, oldest first. -> {prompts: [{index, time, text, files}], total, matched}"""
    needle = (query or '').casefold().strip()
    found, total = [], 0
    for index, event in enumerate(events):
        if not is_prompt(event):
            continue
        total += 1
        text = prompt_text(event)
        if needle and needle not in text.casefold():
            continue
        found.append({'index': index, 'time': event.get('time', ''), 'text': text[:SHOWN], 'files': len(event.get('images') or [])})
    return {'prompts': found[-limit:], 'total': total, 'matched': len(found)}
