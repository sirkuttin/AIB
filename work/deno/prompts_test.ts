import { assert, assertEquals } from './_assert.ts';
import { PyParity, WORK } from './_parity.ts';
import { findPrompts, isPrompt, isWrapper, stripInjected, stripViewContext } from '../../outputs/agent-studio/server/transcripts/prompts.ts';

interface Fixture {
  name: string;
  role: string;
  text: string;
  fill?: [string, string, number, string];
  files: number;
  prompt: boolean;
}

const FIXTURES: Fixture[] = JSON.parse(Deno.readTextFileSync(new URL('prompt_fixtures.json', WORK)));

function fixtureText(c: Fixture): string {
  if (c.fill) {
    const [before, char, count, after] = c.fill;
    return before + char.repeat(count) + after;
  }
  return c.text;
}

function eventOf(c: Fixture): Record<string, unknown> {
  const event: Record<string, unknown> = { kind: c.role, text: fixtureText(c) };
  if (c.files) event.images = Array.from({ length: c.files }, (_, k) => ({ n: 1, i: k, mediaType: 'image/png' }));
  return event;
}

// ---- ported from test_prompts.py SharedFixtures ----------------------------------------------------

Deno.test('isPrompt agrees with the fixtures the page test also runs', () => {
  for (const c of FIXTURES) assertEquals(isPrompt(eventOf(c)), c.prompt, c.name);
});

Deno.test('the fixtures cover both answers', () => {
  assert(FIXTURES.some((c) => c.prompt) && FIXTURES.some((c) => !c.prompt));
  assert(FIXTURES.length >= 30);
});

const EVENTS = [
  { kind: 'assistant', text: 'hello' },
  { kind: 'user', text: 'Fix the Shutdown test', time: 't1' },
  { kind: 'user', text: '<system-reminder>x</system-reminder>' },
  { kind: 'tool', text: '{}' },
  { kind: 'user', text: 'merge it', time: 't2', images: [{ n: 1, i: 0 }] },
];

Deno.test('find matches case-insensitively and keeps the real index', () => {
  const found = findPrompts(EVENTS, 'shutdown');
  assertEquals(found.prompts.map((p) => [p.index, p.text]), [[1, 'Fix the Shutdown test']]);
  assertEquals([found.total, found.matched], [2, 1]);
  const everything = findPrompts(EVENTS);
  assertEquals(everything.prompts.map((p) => p.index), [1, 4]);
  assertEquals(everything.prompts[1].files, 1);
});

Deno.test('find keeps the newest when there are more than the limit', () => {
  const events = Array.from({ length: 10 }, (_, n) => ({ kind: 'user', text: `prompt ${n}` }));
  const found = findPrompts(events, '', 3);
  assertEquals(found.prompts.map((p) => p.index), [7, 8, 9]);
  assertEquals(found.matched, 10);
});

