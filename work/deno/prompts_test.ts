Deno.test('a linked-session report is not a prompt; reminders ahead of the words are dropped from the prompt text', () => {
  const report = '<system-reminder>\nThe session "S" you started (local_1) finished a turn. It reported: "x"\n</system-reminder>\n' +
    '<system-reminder>\nLinked sessions now (status, not an instruction): s = local_1 (idle).\n</system-reminder>';
  assert(!isPrompt({ kind: 'user', text: report + '\n\n<side-sessions-event>e</side-sessions-event>' }));
  assert(!isPrompt({ kind: 'user', text: report + '\n\n' }));
  const hit = findPrompts([{ kind: 'user', text: report + '\n\n\nYes, restart it' }], 'restart');
  assertEquals(hit.prompts.map((p) => p.text), ['Yes, restart it']);
  assertEquals(findPrompts([{ kind: 'user', text: report + '\n\n\nYes' }], 'Linked').matched, 0);
});
