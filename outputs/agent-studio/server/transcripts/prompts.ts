/**
 * Which saved user events are prompts (something the user said), and a search over them: the Prompts view's find box (prompts.py).
 *
 * isPrompt() is the server twin of ChatViews.isPrompt in views.js (which uses StreamUI.classifyUser and stripViewContext in
 * stream-ui.js). They must agree: work/prompt_fixtures.json holds the shared cases. The patterns are the page's own JavaScript
 * ones, so JavaScript's whitespace set, ASCII word boundaries and end-of-text `$` hold here without translation.
 */
import { clip, isDict, isInt, isStr, pyLen } from '../core/py.ts';

const VIEW_CONTEXT_TEST = /<artifact-view-context\b/i;
const VIEW_CONTEXT = /\s*<artifact-view-context\b[^>]*>[\s\S]*?<\/artifact-view-context\s*>\s*/gi;
const AGENT_MESSAGE =
  /^(?:Another Claude session sent a message:\s*)?<(agent-message|cross-session-message)\b([^>]*)>([\s\S]*?)<\/\1>\s*([\s\S]*)$/i;
const TEAMMATE = /^<teammate-message\b([^>]*)>([\s\S]*?)<\/teammate-message>$/i;
const HANDBACK = /^\s*\[Subagent hand-back\]/i;
const REPORT_FOLLOWS = /The report follows:/i;
const TRAILER = /^(?:That\s+[“"']?other Claude session|This came from another Claude session)/i;
// Whole user turns the harness writes in plain text (StreamUI.wholeNote): only these exact lead-ins, never one quoted further down.
const HARNESS_TEXT = [
  /^(?:<[a-z][\w-]*\s*\/>\s*)*(?:The summarized conversation included Artifact content written by people other than you\b[^\n]*\s*)?This session is being continued from a previous conversation\b/i,
  /^\[SYSTEM NOTIFICATION - NOT USER INPUT\]/,
  /^\[handback-send-enforce\]/,
  /^Base directory for this skill:/i,
  /^The coordinator sent a message while you were working:\s*[\s\S]*?\s*Address this before completing your current task\.$/i,
];
const TASK_NOTE = /<task-notification\b[^>]*>[\s\S]*?<\/task-notification>/gi;
const TASK_NOTE_START = /^<task-notification\b/i;
// Wrapper blocks the agent's harness injects into a user turn: the same list and peeling as StreamUI (stream-ui.js).
const INJECTED_TAGS = 'system-reminder|side-sessions-event|user-prompt-submit-hook|hook-output|session-start-hook|' +
  'post-tool-use-hook|pre-tool-use-hook|stop-hook|ide_opened_file|ide_selection|ide_diagnostics|environment_details|' +
  'system_instruction|cross-session-message|local-command-caveat|local-command-stdout|local-command-stderr|fork-boilerplate';
const INJECTED_START = new RegExp('^<(?:' + INJECTED_TAGS + ')(?![\\w-])', 'i');
// A body never contains its own closing tag, so a match cannot run across the person's words into a later block.
const BLOCK = '<(' + INJECTED_TAGS + ')(?![\\w-])[^>]*>((?:(?!</\\1\\s*>)[\\s\\S])*)</\\1\\s*>';
const INJECTED_LEAD = new RegExp('^\\s*' + BLOCK, 'i');
const INJECTED_TAIL = new RegExp(BLOCK + '\\s*$', 'i');
const BOILERPLATE = new RegExp(
  '^\\s*(?:this session is being continued from a previous conversation|' +
    'caveat:\\s*the messages below were generated by the user while running local commands|' +
    '\\[request interrupted by user|base directory for this skill:|the user opened the file|' +
    '<local-command-|continue from where you left off)',
  'i',
);
/** classifyUser ignores longer text (it is then a prompt, as in the page). Counted in code points, as Python's len(). */
export const MAX_CLASSIFIED = 500000;
/** Characters of a prompt the search returns. */
export const SHOWN = 300;

/** Python's str.strip() with no argument: Unicode whitespace (differs from String.trim at \x1c-\x1f, \x85 and \ufeff). */
const PY_SPACE = '[\\t\\n\\x0b\\x0c\\r\\x1c-\\x1f \\x85\\xa0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000]';
const PY_STRIP = new RegExp(`^${PY_SPACE}+|${PY_SPACE}+$`, 'g');

/** Python's str.casefold(), closely enough for a substring search (ß -> ss, ſ -> s, final sigma, ligatures). */
function casefold(value: string): string {
  return value.toUpperCase().toLowerCase();
}

/** Drop the desktop app's <artifact-view-context> blocks from a user turn (display only). Non-strings come back unchanged. */
export function stripViewContext(text: unknown): unknown {
  if (!isStr(text) || !VIEW_CONTEXT_TEST.test(text)) return text;
  return text.replace(VIEW_CONTEXT, ' ').trim();
}

/** Leading and trailing injected blocks off `text`: the trimmed rest and how many blocks came off (StreamUI.peelInjected). */
function peelInjected(text: string): { rest: string; count: number } {
  let s = text, m: RegExpExecArray | null, count = 0;
  while ((m = INJECTED_LEAD.exec(s))) {
    s = s.slice(m[0].length);
    count += 1;
  }
  while ((m = INJECTED_TAIL.exec(s))) {
    s = s.slice(0, m.index);
    count += 1;
  }
  return { rest: s.trim(), count };
}

/** StreamUI.stripInjected: the person's words of a turn, injected blocks at either end dropped ('' when nothing else is left). */
export function stripInjected(text: string): string {
  if (!/<[a-z]/i.test(text)) return text;
  const s = text.trim(); // longer text is left whole, as isWrapper leaves it
  if (s.length > MAX_CLASSIFIED && pyLen(s) > MAX_CLASSIFIED) return text;
  if (wholeWrapper(s)) return text; // a relayed message or harness text as a whole: not words with blocks peeled off its ends
  const p = peelInjected(text);
  return p.count ? p.rest : text;
}

/** StreamUI.classifyUser(text) !== null: the whole text is an injected note (agent message, hand-back, task notice, reminder). */
export function isWrapper(text: string): boolean {
  const s = text.trim();
  if (!s || (s.length > MAX_CLASSIFIED && pyLen(s) > MAX_CLASSIFIED)) return false;
  if (wholeWrapper(s)) return true;
  if (INJECTED_START.test(s)) {
    const p = peelInjected(s);
    if (p.count && !p.rest) return true;
  }
  return false;
}

/** isWrapper without the "only injected blocks" case: the trimmed `s` is one known wrapper or harness text (StreamUI.wholeNote). */
function wholeWrapper(s: string): boolean {
  const m = AGENT_MESSAGE.exec(s);
  if (m) {
    const rest = m[4].trim();
    if (!rest || TRAILER.test(rest)) return true;
  }
  if (HARNESS_TEXT.some((re) => re.test(s))) return true;
  if (TEAMMATE.test(s)) return true;
  if (HANDBACK.test(s) && REPORT_FOLLOWS.test(s)) return true;
  return !s.replace(TASK_NOTE, '').trim() && TASK_NOTE_START.test(s);
}

/** The event carries at least one saved file reference ({n, i} integers). */
export function hasFiles(event: Record<string, unknown>): boolean {
  const images = event.images;
  if (!Array.isArray(images)) return false;
  return images.some((im) => isDict(im) && isInt(im.n) && isInt(im.i));
}

/** The event's text without view context, or '' when it has none. */
export function promptText(event: Record<string, unknown>): string {
  const value = event.text;
  return isStr(value) ? stripInjected(stripViewContext(value) as string) : '';
}

/** A saved user event that is something the user said: not an injected note, boilerplate or an interrupt. */
export function isPrompt(event: unknown): boolean {
  if (!isDict(event) || event.kind !== 'user') return false;
  if (hasFiles(event)) return true;
  const text = promptText(event);
  if (!text || !text.trim()) return false;
  if (isWrapper(text)) return false;
  return !BOILERPLATE.test(text);
}

export interface PromptHit {
  index: number;
  time: unknown;
  text: string;
  files: number;
}

/** Python's len() on the JSON values an event's images field can hold. */
function pyLenOf(value: unknown): number {
  if (!value) return 0;
  if (Array.isArray(value)) return value.length;
  if (isStr(value)) return pyLen(value);
  if (isDict(value)) return Object.keys(value).length;
  throw new TypeError(`object of type '${typeof value === 'boolean' ? 'bool' : isInt(value) ? 'int' : 'float'}' has no len()`);
}

/**
 * The user's prompts in `events` (the same list /api/transcript pages through, so `index` is the real event index) whose text
 * contains `query` (case-insensitive). Newest `limit` kept, oldest first. -> {prompts: [{index, time, text, files}], total, matched}
 */
export function findPrompts(
  events: unknown[],
  query: string | null = '',
  limit = 200,
): { prompts: PromptHit[]; total: number; matched: number } {
  const needle = casefold(query || '').replace(PY_STRIP, '');
  const found: PromptHit[] = [];
  let total = 0;
  events.forEach((event, index) => {
    if (!isPrompt(event)) return;
    const ev = event as Record<string, unknown>;
    total += 1;
    const text = promptText(ev);
    if (needle && !casefold(text).includes(needle)) return;
    found.push({ index, time: 'time' in ev ? ev.time : '', text: clip(text, SHOWN), files: pyLenOf(ev.images) });
  });
  return { prompts: found.slice(-limit), total, matched: found.length };
}
