// Studio's note to the agent in front of a prompt (worktree live sync). The agent's saved history keeps it; no view shows it.
const STUDIO_CONTEXT = new RegExp(`<studio-context>[\\s\\S]*?</studio-context>[${S}]*`, 'gu');

export function stripStudioContext<T>(text: T): T | string {
  return typeof text === 'string' && text.includes('<studio-context>') ? text.replace(STUDIO_CONTEXT, '') : text;
}

export function contentText(content: Json): string {
  if (typeof content === 'string') return stripStudioContext(content) as string;
  if (!Array.isArray(content)) return '';
  return content.filter((b) => isDict(b) && b.type === 'text').map((b) => stripStudioContext(pyStr(dget(b as Dict, 'text', '')))).join(
    '\n',
  );
}

// ---- readable conversation titles -------------------------------------------------------------
export const TITLE_LIMIT = 90;
// Wrapper blocks that agents and the CLI inject into user turns. The block and everything inside it is dropped.
const NOISE_TAGS = [
  'system-reminder',
  'command-message',
  'local-command-caveat',
  'local-command-stdout',
  'local-command-stderr',
  'user-prompt-submit-hook',
  'ide_opened_file',
  'ide_selection',
  'ide_diagnostics',
  'task-notification',
  'side-sessions-event',
  'bash-input',
  'bash-stdout',
  'bash-stderr',
  'command-stdout',
  'hook-output',
  'environment_details',
  'system_instruction',
  'artifact-view-context',
  'studio-context',
  'cross-session-message',
  'session-start-hook',
  'post-tool-use-hook',
  'pre-tool-use-hook',
  'stop-hook',
  'fork-boilerplate',
].join('|');
const NOISE_BLOCK = new RegExp(`<(${NOISE_TAGS})(?![${W}])[^>]*>[\\s\\S]*?</\\1[${S}]*>`, 'giu');
const NOISE_OPEN = new RegExp(`<(${NOISE_TAGS})(?![${W}])[^>]*>[\\s\\S]*$`, 'iu'); // truncated block
const COMMAND_NAME = new RegExp(`<command-name>[${S}]*([\\s\\S]*?)[${S}]*</command-name>`, 'iu');
const COMMAND_ARGS = new RegExp(`<command-args>[${S}]*([\\s\\S]*?)[${S}]*</command-args>`, 'iu');
const COMMAND_TAGS = /<command-(?:name|args|message)>[\s\S]*?<\/command-(?:name|args|message)>/giu;
// Messages that are scaffolding rather than something the user typed; the next real user message is used instead.
const BOILERPLATE = new RegExp(
  `^[${S}]*(?:` +
    // a compaction summary, also behind self-closing tags and the note about others' Artifact content
    `(?:<[${W}-]+[${S}]*/>[${S}]*)*(?:the summarized conversation included artifact content[^\\n]*[${S}]*)?` +
    'this session is being continued from a previous conversation|' +
    'another claude session sent a message:|' +
    'the coordinator sent a message while you were working:|' +
    '\\[system notification - not user input\\]|' +
    '\\[handback-send-enforce\\]|' +
    `caveat:[${S}]*the messages below were generated by the user while running local commands|` +
    '\\[request interrupted by user|' +
    'base directory for this skill:|' +
    'the user opened the file|' +
    '<local-command-|' +
    'continue from where you left off|' +
    `\\[image(?: #${'[' + D + ']'}+)?\\][${S}]*$)`,
  'iu',
);

const FENCE = /^[`~]{3,}[^\n]*$/u;
const RULE = new RegExp(`^[-=_*#${S}]{3,}$`, 'u');
const TAG = /<[^>\n]{0,200}>/gu;
const IMAGE_MD = /!\[([^\]]*)\]\([^)]*\)/gu;
const LINK_MD = /\[([^\]]+)\]\([^)]*\)/gu;
const MARKER = new RegExp(`^[${S}]*(?:#{1,6}[${S}]+|>+[${S}]*|[-*+][${S}]+|[${D}]+[.)][${S}]+)`, 'u');
const EMPHASIS = /(\*\*|__|~~|`+)/gu;
const LONE_MARK = new RegExp(`(?<![${W}])[*_](?=[^${S}])|(?<=[^${S}])[*_](?![${W}])`, 'gu');
const SPACES = new RegExp(`[${S}]+`, 'gu');

/** Plain-text, single-line, length-capped version of any text. Markdown and tags are removed, never rendered. */
export function tidyTitle(text: Json, limit = TITLE_LIMIT): string {
  if (typeof text !== 'string') return '';
  const lines = splitlines(text).map((l) => pyStrip(l)).filter((ln) => ln && !FENCE.test(ln) && !RULE.test(ln));
  const first = lines[0] ?? '';
  // A short first line followed by more text reads better as a whole ("Fix this:" + body); a full line is a title already.
  let joined = pyLen(first) >= 16 ? first : lines.slice(0, 3).join(' ');
  joined = joined.replace(TAG, ' ');
  joined = joined.replace(IMAGE_MD, '$1');
  joined = joined.replace(LINK_MD, '$1');
  joined = joined.replace(MARKER, '');
  joined = joined.replace(EMPHASIS, '');
  joined = joined.replace(LONE_MARK, '');
  joined = pyStrip(joined.replace(SPACES, ' '), ' \t-:|');
  if (pyLen(joined) > limit) {
    const cut = [...joined].slice(0, limit);
    const space = cut.lastIndexOf(' ');
    joined = rstrip((space >= limit * 0.6 ? cut.slice(0, space) : cut).join(''), ' ,;:.-') + '\u2026';
  }
  return joined;
}

/** The title candidate for one user message, or '' when the message is scaffolding (reminders, commands, continuations). */
export function cleanPrompt(text: Json): string {
  if (typeof text !== 'string' || !pyStrip(text)) return '';
  const command = COMMAND_NAME.exec(text);
  let commandTitle = '';
  if (command) {
    const args = COMMAND_ARGS.exec(text);
    commandTitle = pyStrip(command[1] + ' ' + (args ? args[1] : ''));
  }
  let body = text.replace(NOISE_BLOCK, '').replace(NOISE_OPEN, '');
  body = pyStrip(body.replace(COMMAND_TAGS, ''));
  if (body && BOILERPLATE.test(body)) return '';
  if (!body) return tidyTitle(commandTitle);
  return tidyTitle(body);
}

/** Best readable title: owner or adapter titles first, then Claude's summary, then the first real user message. */
export function deriveTitle(meta: Dict): string {
  for (const key of ['customTitle', 'aiTitle', 'agentTitle', 'summaryTitle']) {
    const value = tidyTitle(dget(meta, key));
    if (value) return value;
  }
  return (or(dget(meta, 'prompt'), '') as string);
}

export const IMAGE_TYPES = new Set(['image/png', 'image/jpeg', 'image/gif', 'image/webp']);
export const IMAGE_LIMIT = 10 * 1024 * 1024;
// Text the CLI adds next to a pasted image ("[Image #1]", "[Image: source: C:\...\16.png]"); the picture itself is shown instead.
export const IMAGE_REF = new RegExp(
  `^(?:[${S}]*\\[Image(?: #[${D}]+)?(?::[${S}]*source:[${S}]*[^\\]\\n]+)?\\][${S}]*)+$`,
  'u',
);

function inImageTypes(media: Json): boolean {
  if (Array.isArray(media) || isDict(media)) throw new PyTypeError(`unhashable type: '${pyTypeName(media)}'`);
  return typeof media === 'string' && IMAGE_TYPES.has(media);
}

/** (media type, base64 data) of a transcript image block, or [null, null]. Claude Code: source {type: base64, media_type, data};
 * OMP and ACP: {mimeType, data}. */
export function imageBlock(block: Dict): [string | null, string | null] {
  const source = isDict(block.source) ? block.source : null;
  let media: Json;
  let data: Json;
  if (source && source.type === 'base64') {
    media = dget(source, 'media_type');
    data = dget(source, 'data');
  } else {
    media = or(dget(block, 'mimeType'), dget(block, 'media_type'));
    data = dget(block, 'data');
  }
  if (
    inImageTypes(media) && typeof data === 'string' && data &&
    (data.length <= IMAGE_LIMIT * 4 / 3 + 4 || pyLen(data) <= Math.floor(IMAGE_LIMIT * 4 / 3) + 4)
  ) {
    return [media as string, data];
  }
  return [null, null];
}

/** Claude Code saves a message sent while the agent works as an attachment {type: queued_command, commandMode: prompt, prompt};
 * read it as an ordinary user message. */
export function asMessage(row: Dict): Dict {
  const att = row.type === 'attachment' ? dget(row, 'attachment') : null;
  if (isDict(att) && att.type === 'queued_command' && dget(att, 'commandMode', 'prompt') === 'prompt') {
    const prompt = dget(att, 'prompt');
    if ((typeof prompt === 'string' || Array.isArray(prompt)) && truthy(prompt)) {
      return {
        type: 'user',
        timestamp: or(dget(row, 'timestamp'), dget(att, 'timestamp', '')),
        queued: true,
        message: { role: 'user', content: prompt },
      };
    }
  }
  return row;
}

const NOTE = /<task-notification>([\s\S]*?)<\/task-notification>/gu;
const NOTE_ID = new RegExp(`<task-id>[${S}]*([^<${S}]+)[${S}]*</task-id>`, 'u');
const NOTE_STATUS = new RegExp(`<status>[${S}]*([^<${S}]+)[${S}]*</status>`, 'u');

/** Background tasks a queued task-notification reports as finished (Claude Code delivers these mid-turn; only ids matter). */
export function finishedTasks(row: Dict): string[] {
  const att = row.type === 'attachment' ? dget(row, 'attachment') : null;
  if (!(isDict(att) && att.type === 'queued_command' && att.commandMode === 'task-notification')) return [];
  const prompt = dget(att, 'prompt');
  const raw = typeof prompt === 'string' ? prompt : Array.isArray(prompt) ? contentText(prompt) : '';
  const ids: string[] = [];
  for (const match of raw.matchAll(NOTE)) {
    const job = NOTE_ID.exec(match[1]);
    const status = NOTE_STATUS.exec(match[1]);
    if (job && !(status && status[1].toLowerCase() === 'running')) ids.push(job[1]);
  }
  return ids;
}

export function normalize(row: Dict, number: number): Event[] {
  const done = finishedTasks(row);
  if (done.length) {
    return [{
      id: `${number}-done`,
      kind: 'task-done',
      label: 'Background task finished',
      text: done.join(' '),
      time: dget(row, 'timestamp', ''),
    }];
  }
  row = asMessage(row);
  let stamp = dget(row, 'timestamp', '');
  if (row.type === 'session_init') {
    return truthy(dget(row, 'task'))
      ? [{ id: `${number}-task`, kind: 'assignment', time: stamp, text: clipped(dget(row, 'task', '')), label: 'Assignment' }]
      : [];
  }
  if (!['message', 'custom_message', 'user', 'assistant'].includes(row.type as string)) return [];
  const msg = dget(row, 'message', row);
  const role = get(msg, 'role', 'notice');
  const content = get(msg, 'content', []);
  const m = msg as Dict;
  stamp = or(stamp, dget(m, 'timestamp', ''));
  let events: Event[] = [];
  if (role === 'toolResult') {
    events.push({
      kind: truthy(dget(m, 'isError')) ? 'error' : 'result',
      label: dget(m, 'toolName', 'Tool result'),
      text: clipped(contentText(content)),
      callId: dget(m, 'toolCallId'),
      time: stamp,
    });
  } else if (typeof content === 'string') {
    const shown = role === 'user' ? stripStudioContext(content) as string : content;
    if (shown || !content) events.push({ kind: role, label: pyTitle(role), text: clipped(shown), time: stamp });
  } else if (Array.isArray(content)) {
    content.forEach((block, index) => {
      if (!isDict(block)) return;
      const kind = dget(block, 'type');
      if (kind === 'toolCall' || kind === 'tool_use') {
        events.push({
          kind: 'tool',
          label: dget(block, 'name', 'Tool'),
          time: stamp,
          text: clipped(Object.hasOwn(block, 'arguments') ? block.arguments : dget(block, 'input', {})),
          callId: dget(block, 'id'),
          intent: dget(block, 'intent', ''),
        });
      } else if (kind === 'tool_result') {
        const event: Event = {
          kind: truthy(dget(block, 'is_error')) ? 'error' : 'result',
          label: 'Tool result',
          time: stamp,
          callId: dget(block, 'tool_use_id'),
          text: clipped(contentText(dget(block, 'content', ''))),
        };
        // Pictures a tool returned (a screenshot): addresses only, fetched on demand like pasted ones.
        const inner = dget(block, 'content');
        const shots: Dict[] = [];
        (Array.isArray(inner) ? inner : []).forEach((part, j) => {
          if (isDict(part) && dget(part, 'type') === 'image') {
            const media = imageBlock(part)[0];
            if (media) shots.push({ n: number, i: index, j, mediaType: media });
          }
        });
        if (shots.length) event.images = shots;
        events.push(event);
      } else if (kind === 'text' || kind === 'thinking') {
        let text = dget(block, kind === 'text' ? 'text' : 'thinking', '');
        if (kind === 'text' && role === 'user') text = stripStudioContext(text);
        if (kind === 'text' && role === 'user' && IMAGE_REF.test(needStr(text))) return;
        if (truthy(text)) {
          events.push({
            kind: kind === 'text' ? role : 'thinking',
            label: kind === 'text' ? pyTitle(role) : 'Thinking',
            time: stamp,
            text: clipped(text),
          });
        }
      } else if (kind === 'image') {
        const [media] = imageBlock(block);
        if (media) {
          // The picture is fetched on demand from /api/transcript/image; only its address travels with the page.
          events.push({ kind: role, label: pyTitle(role), time: stamp, text: '', images: [{ n: number, i: index, mediaType: media }] });
        } else {
          events.push({
            kind: role,
            label: 'Image attachment',
            time: stamp,
            text: '[Image could not be shown: unsupported type or too large.]',
          });
        }
      }
    });
  }
  // A pasted screenshot and the words typed with it are one message: hang the pictures on that message's text.
  const pictures = events.filter((e) => Object.hasOwn(e, 'images'));
  const text = events.find((e) => e.kind === role && !Object.hasOwn(e, 'images') && truthy(e.text));
  if (pictures.length && text !== undefined) {
    text.images = pictures.flatMap((e) => e.images as Dict[]);
    events = events.filter((e) => !Object.hasOwn(e, 'images') || e === text);
  }
  events.forEach((event, i) => (event.id = `${number}-${i}`));
  return events;
}

/** Claude Code names a project's transcript folder after the folder path with every non-alphanumeric turned into '-'. */
export function encoded(path: string): string {
  return path.replace(/[^A-Za-z0-9]/gu, '-');
}

/** The folder (or a parent of a folder) among cwds whose encoding names the transcript's project folder, else null.
 * Git Bash style paths (/c/Users/...) are read as Windows paths (C:\Users\...) on Windows. */
export function projectMatch(cwds: Json[], transcript: string): string | null {
  const names = new Set(pureParents(nativePath(transcript)).slice(0, 4).map(pureName));
  for (let cwd of cwds) {
    if (typeof cwd !== 'string' || !cwd) continue;
    const msys = WINDOWS ? /^\/([A-Za-z])(\/[^\n]*)?(?=\n?$)/.exec(cwd) : null; // on POSIX /c/x is a real folder
    if (msys) cwd = msys[1].toUpperCase() + ':' + (msys[2] || '/').replaceAll('/', '\\');
    const c = cwd as string;
    const pure = purePath(c, /^[A-Za-z]:/.test(c) || c.includes('\\')); // a ':' elsewhere is legal in POSIX names
    for (const candidate of [pure, ...pureParents(pure)]) {
      const text = pureStr(candidate);
      if (!['.', '/', '\\'].includes(text) && names.has(encoded(text))) return text;
    }
  }
  return null;
}

/** The folder a chat belongs to: the visited folder (or parent) whose encoding names the transcript folder, else the first seen. */
export function projectCwd(meta: Dict, transcript: string): Json {
  const cwds = or(dget(meta, '_cwds'), truthy(dget(meta, 'cwd')) ? [meta.cwd] : []) as Json[];
  return projectMatch(cwds, transcript) ?? (cwds.length ? cwds[0] : dget(meta, 'cwd'));
}

const TITLE_FIELDS: Record<string, [string, string]> = {
  title: ['title', 'agentTitle'],
  'ai-title': ['aiTitle', 'aiTitle'],
  'custom-title': ['customTitle', 'customTitle'],
  summary: ['summary', 'summaryTitle'],
};

export function updateMetadata(meta: Dict, row: Json): void {
  const kind = get(row, 'type');
  const r = row as Dict;
  if (kind === 'session') {
    for (const k of ['cwd', 'id', 'parentSession', 'timestamp']) meta[k] = dget(r, k);
  } else if (typeof kind === 'string' && Object.hasOwn(TITLE_FIELDS, kind)) {
    const field = TITLE_FIELDS[kind];
    const value = typeof dget(r, field[0]) === 'string' ? dget(r, field[0]) : dget(r, 'title');
    if (typeof value === 'string' && pyStrip(value)) meta[field[1]] = value;
  } else if (kind === 'model_change') {
    meta.model = dget(r, 'model', '');
  } else if (kind === 'session_init') {
    meta.model = dget(r, 'resolvedModel', dget(meta, 'model', ''));
    const task = dget(r, 'task');
    if (typeof task === 'string' && pyStrip(task) && !Object.hasOwn(meta, 'task')) meta.task = clip(splitlines(pyStrip(task))[0], 200);
  } else if (kind === 'message' && isDict(r.message)) {
    const msg = r.message;
    if (dget(msg, 'role') === 'user' && !Object.hasOwn(meta, 'prompt') && !truthy(dget(r, 'isMeta'))) {
      const prompt = cleanPrompt(contentText(dget(msg, 'content', '')));
      if (prompt) meta.prompt = prompt;
    }
  } else if (kind === 'user' || kind === 'assistant') {
    if (truthy(dget(r, 'agentId'))) meta.agentId = r.agentId;
    const cwd = dget(r, 'cwd');
    if (typeof cwd === 'string' && cwd) {
      // The agent can cd anywhere during a chat; keep every folder seen (bounded) and pick the chat's project later.
      if (!Object.hasOwn(meta, '_cwds')) meta._cwds = [];
      const seen = meta._cwds as Json[];
      if (!seen.includes(cwd) && seen.length < 64) seen.push(cwd);
      if (!Object.hasOwn(meta, 'cwd')) meta.cwd = cwd;
    }
    if (truthy(dget(r, 'sessionId'))) meta.id = r.sessionId;
    if (!Object.hasOwn(meta, 'timestamp')) meta.timestamp = dget(r, 'timestamp');
    const msg = dget(r, 'message', {});
    if (isDict(msg) && truthy(dget(msg, 'model'))) meta.model = msg.model;
    if (kind === 'user' && !Object.hasOwn(meta, 'prompt') && !truthy(dget(r, 'isMeta')) && !truthy(dget(r, 'isSidechain'))) {
      const prompt = cleanPrompt(isDict(msg) ? contentText(dget(msg, 'content', '')) : '');
      if (prompt) meta.prompt = prompt;
    }
  }
}

// The page folds a chat's plan card, pinned plan and "N running tasks" from the rows it holds (plan-ui.js). A long turn can push
// the update_plan call that set the plan out of the newest page, so the transcript remembers which events that fold reads.
export const PLAN_TOOL = /(?:^|__)update_plan(?=\n?$)|^TodoWrite(?=\n?$)/iu;
export const WRAP_TOOL = /(?:^|__)ccd_turn__wrap_up(?=\n?$)/u;
export const BG_LAUNCH = new RegExp(
  `^[${S}"{\\[]*(?:Async agent launched|Command running in background with ID|Backgrounded as job)`,
  'iu',
);
export const BG_ID = new RegExp(`agentId:[${S}]*([${W}-]+)|in background with ID:?[${S}]*([${W}-]+)`, 'iu');
export const FINISH_TEXT = new RegExp(`<task-notification(?![${W}])|Successfully (?:stopped|killed) task|\\[Subagent hand-back\\]`, 'iu');
export const CONTEXT_LIMIT = 1500;
const STOPPED = new RegExp(`Successfully (?:stopped|killed) task:?[${S}]*([${W}-]+)`, 'giu');
const SENDER = new RegExp(`<agent-message[${S}]+from="([${W}-]+)"`, 'iu');
const NOTE_ANY = new RegExp(`<task-notification(?![${W}])[^>]*>([\\s\\S]*?)</task-notification>`, 'giu');
const NOTE_ID_I = new RegExp(`<task-id>[${S}]*([^<${S}]+)[${S}]*</task-id>`, 'iu');
const NOTE_STATUS_I = new RegExp(`<status>[${S}]*([^<${S}]+)[${S}]*</status>`, 'iu');
const BACKGROUND_TRUE = new RegExp(`"run_in_background"[${S}]*:[${S}]*true`, 'u');

/** Task ids the page's fold treats as finished in this text (mirrors finishedIds in plan-ui.js). */
export function finishedIds(text: string): string[] {
  const ids = [...text.matchAll(STOPPED)].map((m) => m[1]);
  if (text.includes('[Subagent hand-back]')) {
    const sender = SENDER.exec(text);
    if (sender) ids.push(sender[1]);
  }
  for (const match of text.matchAll(NOTE_ANY)) {
    const job = NOTE_ID_I.exec(match[1]);
    const status = NOTE_STATUS_I.exec(match[1]);
    if (job && !(status && status[1].toLowerCase() === 'running')) ids.push(job[1]);
  }
  return ids;
}

export type Mark = 'set' | 'patch' | 'wrap' | 'launch' | 'finish' | 'user';

/** What the page's plan fold would read in this event, or null. `flagged` holds the ids of run_in_background calls (hkey). */
export function planMark(event: Event, flagged: Set<string>): Mark | null {
  const kind = event.kind;
  const text = or(event.text, '') as string;
  if (kind === 'tool') {
    const label = pyStr(or(event.label, ''));
    if (PLAN_TOOL.test(label)) {
      let data: Json;
      try {
        data = JSON.parse(text);
      } catch {
        return null;
      }
      if (isDict(data)) {
        if (['todos', 'items', 'plan'].some((k) => Array.isArray(dget(data as Dict, k)))) return 'set';
        const start = dget(data, 'start');
        if (truthy(dget(data, 'advance')) || Array.isArray(dget(data, 'done')) || Number.isInteger(start) || typeof start === 'boolean') {
          return 'patch';
        }
      }
      return null;
    }
    if (WRAP_TOOL.test(label)) return 'wrap';
    if (BACKGROUND_TRUE.test(text)) {
      if (truthy(event.callId)) flagged.add(hkey(event.callId));
      return 'launch';
    }
    return null;
  }
  if (kind === 'result' || kind === 'error') {
    if (BG_LAUNCH.test(text) || flagged.has(hkey(event.callId ?? null))) return 'launch';
    return FINISH_TEXT.test(text) ? 'finish' : null;
  }
  if (kind === 'task-done') return 'finish';
  if (kind === 'user') return 'user';
  return null;
}

