async function readText(path: string): Promise<string | null> {
  try {
    return await Deno.readTextFile(path);
  } catch {
    return null;
  }
}

async function exists(path: string): Promise<boolean> {
  try {
    await Deno.stat(path);
    return true;
  } catch {
    return false;
  }
}

/** Did AIB write this Markdown file (its first line is AIB's note)? Only such a file can be a doc's copy. */
async function aibWritten(path: string): Promise<boolean> {
  const text = await readText(path);
  return text !== null && NOTE_LINE.test(text);
}

/** A path inside the project, project-relative with forward slashes. */
function relTo(projectRoot: string, path: string): string {
  const root = projectRoot.replace(/[\\/]+$/, '');
  const inside = pathKey(path).startsWith(pathKey(root + sep)) ? path.slice(root.length + 1) : path;
  return inside.replace(/\\/g, '/');
}

/** The files a doc owns: doc.aibdoc, its pages' copies (`copies`: their paths), its assets folder and every file in it. */
async function ownedPaths(projectRoot: string, dir: string, copies: string[]): Promise<OwnedPaths> {
  const owned = [`${dir}${sep}${AIBDOC}`, ...copies];
  const walk = async (folder: string) => {
    try {
      for await (const e of Deno.readDir(folder)) {
        const path = `${folder}${sep}${e.name}`;
        if (e.isDirectory) await walk(path);
        else owned.push(path);
      }
    } catch { /* no assets */ }
  };
  if (await exists(`${dir}${sep}assets`)) {
    owned.push(`${dir}${sep}assets`);
    await walk(`${dir}${sep}assets`);
  }
  return { dir: relTo(projectRoot, dir), owned: owned.map((p) => relTo(projectRoot, p)) };
}

/** Each page's Markdown copy: NN-<title slug>.md in page order. */
function copyPaths(dir: string, titles: string[]): string[] {
  return titles.map((t, k) => `${dir}${sep}${String(k + 1).padStart(2, '0')}-${slugOf(t)}.md`);
}

/** A node without agentEdit marks (a duplicated page is the user's). */
export function withoutAgentMarks(node: PMJson): PMJson {
  const out: PMJson = { ...node };
  if (Array.isArray(node.marks)) {
    const marks = node.marks.filter((m) => (m as { type?: string }).type !== 'agentEdit');
    if (marks.length) out.marks = marks;
    else delete out.marks;
  }
  if (Array.isArray(node.content)) out.content = node.content.map((c) => withoutAgentMarks(c as PMJson));
  return out;
}

async function isFile(path: string): Promise<boolean> {
  try {
    return (await Deno.stat(path)).isFile;
  } catch {
    return false;
  }
}

export class DocStore {
  readonly docs = new Map<string, OpenDoc>();
  /** This store's run (a restart makes a new one); each doc load adds a count (OpenDoc.epoch). */
  readonly epoch = crypto.getRandomValues(new Uint32Array(1))[0].toString(36);
  #loads = 0;
  #opening = new Map<string, Promise<OpenDoc>>();
  #poll: ReturnType<typeof setInterval> | null = null;

  constructor(readonly stateDir: string, readonly options: StoreOptions = {}) {}

  /** Start polling the open docs' files for edits made outside AIB. */
  start(): void {
    if (this.#poll !== null) return;
    const poll = setInterval(() => {
      for (const d of this.docs.values()) {
        void this.syncMirror(d).catch(() => {});
      }
    }, this.options.pollMs ?? 1000);
    Deno.unrefTimer(poll);
    this.#poll = poll;
  }

  #cacheDir(id: string): string {
    return `${this.stateDir}${sep}docs${sep}cache${sep}${id}`;
  }

  #docsDir(projectRoot: string): string {
    return `${projectRoot}${sep}${this.options.mirrorFolder ?? 'docs'}`;
  }

  /** The doc's folder. */
  docDir(projectRoot: string, name: string): string {
    return `${this.#docsDir(projectRoot)}${sep}${name}`;
  }

  /** The first page's Markdown copy of a doc (before it is open: page 1 of the folder). */
  mirrorPath(projectRoot: string, name: string): string {
    const open = [...this.docs.values()].find((d) => d.name === name && sameRoot(d.projectRoot, projectRoot));
    return open?.mirrorPath ?? `${this.docDir(projectRoot, name)}${sep}01-page-1.md`;
  }

  /** A doc of the old layout (docs/<name>.md, state in <stateDir>/docs/<old id>/) whose name gives this folder name. */
  async #legacy(
    projectRoot: string,
    name: string,
  ): Promise<{ title: string; md: string | null; state: string | null; keepMd?: boolean } | null> {
    let found: { title: string; md: string | null; state: string | null; keepMd?: boolean } | null = null;
    try {
      for await (const e of Deno.readDir(this.#docsDir(projectRoot))) {
        if (!e.isFile || !e.name.toLowerCase().endsWith('.md')) continue;
        const title = e.name.slice(0, -3);
        if (!NAME.test(title) || slugOf(title, 60, 'doc') !== name) continue;
        const path = `${this.#docsDir(projectRoot)}${sep}${e.name}`;
        if (!(await aibWritten(path))) continue; // a user's own docs/x.md is never a doc
        found = { title, md: path, state: null };
        break;
      }
    } catch { /* no docs folder */ }
    try {
      for await (const e of Deno.readDir(`${this.stateDir}${sep}docs`)) {
        if (!e.isDirectory || e.name === 'cache') continue;
        try {
          const meta = JSON.parse(await Deno.readTextFile(`${this.stateDir}${sep}docs${sep}${e.name}${sep}meta.json`));
          if (typeof meta.name !== 'string' || !sameRoot(meta.projectRoot, projectRoot) || slugOf(meta.name, 60, 'doc') !== name) continue;
          const state = `${this.stateDir}${sep}docs${sep}${e.name}`;
          const md = `${this.#docsDir(projectRoot)}${sep}${meta.name}.md`;
          found = { title: meta.name, md: found?.md ?? ((await isFile(md)) ? md : null), state };
          // the old layout's copy goes only when AIB wrote it; a file the user wrote there stays where it is
          if (found.md && !(await aibWritten(found.md))) found.keepMd = true;
          // the old layout's copy is moved only when AIB wrote it; a file the user wrote over it stays where it is
          if (found.md && !(await aibWritten(found.md))) found.keepMd = true;
          break;
        } catch { /* not a doc */ }
      }
    } catch { /* no state yet */ }
    return found;
  }

  /** Is there a doc of this name in the project (its folder, or one of the old layout)? */
  async exists(projectRoot: string, nameValue: unknown): Promise<boolean> {
    const { name } = docRef(nameValue);
    const id = await docId(projectRoot, name);
    if (this.docs.has(id)) return true;
    if (await isFile(`${this.docDir(projectRoot, name)}${sep}${AIBDOC}`)) return true;
    return (await this.#legacy(projectRoot, name)) !== null;
  }

  /**
   * Open a doc. With `create` (Markdown, maybe empty) a new doc is made and refused if one exists; without it a doc that does not
   * exist is refused (`no_doc`). A doc of the old layout is moved to its folder.
   */
  async open(
    projectRoot: string,
    nameValue: unknown,
    create?: string,
  ): Promise<OpenDoc> {
    const { name, title } = docRef(nameValue);
    const id = await docId(projectRoot, name);
    if (create !== undefined && await this.exists(projectRoot, name)) {
      throw new DocRefusal(
        'doc_exists',
        `A doc named "${name}" already exists (docs/${name}/). Read it with doc_read, or pick another name.`,
      );
    }
    if (create !== undefined && await exists(this.docDir(projectRoot, name))) {
      throw new DocRefusal(
        'folder_exists',
        `There is a folder docs/${name}/ already, and it is not a doc: pick another name (AIB never writes into a folder it did not make).`,
      );
    }
    const open = this.docs.get(id);
    if (open) return open;
    if (create === undefined && !(await this.exists(projectRoot, name))) {
      throw new DocRefusal('no_doc', `No doc named "${name}" in this project. doc_list shows the docs; doc_create makes one.`);
    }
    let pending = this.#opening.get(id);
    if (!pending) {
      pending = this.#load(id, projectRoot, name, title, create).finally(() => this.#opening.delete(id));
      this.#opening.set(id, pending);
    }
    return await pending;
  }

  /** The docs of a project: folders with a doc.aibdoc, and docs of the old layout (`legacy`: moved on first open). */
  async list(
    projectRoot: string,
  ): Promise<
    ({
      name: string;
      title: string;
      file: string;
      open: boolean;
      pages?: number;
      rev?: number;
      blocks?: number;
      legacy?: true;
      pageList?: { id: string; title: string }[];
      chat?: string | null;
    } & Partial<OwnedPaths>)[]
  > {
    const found = new Map<
      string,
      { title: string; file: string; pages?: number; legacy?: true; titles?: string[]; pageList?: { id: string; title: string }[] }
    >();
    const docs = this.#docsDir(projectRoot);
    try {
      for await (const e of Deno.readDir(docs)) {
        if (e.isDirectory) {
          const file = `${docs}${sep}${e.name}${sep}${AIBDOC}`;
          const text = await readText(file);
          if (text === null) continue;
          let title = e.name, pages: number | undefined, titles: string[] = [], pageList: { id: string; title: string }[] = [];
          try {
            const aib = parseAib(text);
            title = aib.title || e.name;
            pages = aib.pages.length;
            titles = aib.pages.map((p) => p.title);
            pageList = aib.pages.map((p) => ({ id: p.id, title: p.title }));
          } catch { /* listed; opening it says what is wrong */ }
          found.set(e.name, { title, file, titles, pageList, ...(pages ? { pages } : {}) });
        }
      }
      for await (const e of Deno.readDir(docs)) {
        if (!e.isFile || !e.name.toLowerCase().endsWith('.md') || !NAME.test(e.name.slice(0, -3))) continue;
        if (!(await aibWritten(`${docs}${sep}${e.name}`))) continue; // a user's own docs/x.md is a file, not a doc
        const title = e.name.slice(0, -3), name = slugOf(title, 60, 'doc');
        if (!found.has(name)) found.set(name, { title, file: `${docs}${sep}${e.name}`, legacy: true });
      }
    } catch { /* no docs folder */ }
    try {
      for await (const e of Deno.readDir(`${this.stateDir}${sep}docs`)) {
        if (!e.isDirectory || e.name === 'cache') continue;
        try {
          const meta = JSON.parse(await Deno.readTextFile(`${this.stateDir}${sep}docs${sep}${e.name}${sep}meta.json`));
          if (typeof meta.name !== 'string' || !sameRoot(meta.projectRoot, projectRoot)) continue;
          const name = slugOf(meta.name, 60, 'doc');
          if (!found.has(name)) found.set(name, { title: meta.name, file: `${docs}${sep}${meta.name}.md`, legacy: true });
        } catch { /* not a doc */ }
      }
    } catch { /* no state yet */ }
    const out = [];
    for (const name of [...found.keys()].sort()) {
      const id = await docId(projectRoot, name);
      const doc = this.docs.get(id);
      // the linked chat (the Artifacts picker's "This chat"): the open doc's, else the one its cache remembers
      let chat: string | null = doc ? doc.chat : null;
      if (!doc) {
        try {
          const meta = JSON.parse(await Deno.readTextFile(`${this.#cacheDir(id)}${sep}meta.json`)) as CacheMeta;
          chat = typeof meta.chat === 'string' ? meta.chat : null;
        } catch { /* never opened here */ }
      }
      const { titles, ...f } = found.get(name)!;
      const dir = this.docDir(projectRoot, name);
      const owned = doc
        ? await ownedPaths(projectRoot, doc.dir, [...this.#pagePaths(doc).values()])
        : f.legacy
        ? { dir: relTo(projectRoot, dir), owned: [relTo(projectRoot, f.file)] }
        : await ownedPaths(projectRoot, dir, copyPaths(dir, titles ?? []));
      out.push({
        name,
        ...f,
        ...owned,
        ...(doc
          ? {
            title: doc.title,
            file: doc.file,
            pages: doc.live.pageList().length,
            pageList: doc.live.pageList().map((p) => ({ id: p.id, title: p.title })),
            legacy: undefined,
          }
          : {}),
        chat,
        open: !!doc,
        ...(doc ? { rev: doc.live.rev, blocks: doc.live.blockCount } : {}),
      });
    }
    return out.map((d) => Object.fromEntries(Object.entries(d).filter(([, v]) => v !== undefined)) as typeof d);
  }

  async #readCache(id: string): Promise<{ state: Uint8Array; meta: CacheMeta } | null> {
    try {
      const state = await Deno.readFile(`${this.#cacheDir(id)}${sep}doc.bin`);
      const meta = JSON.parse(await Deno.readTextFile(`${this.#cacheDir(id)}${sep}meta.json`)) as CacheMeta;
      return { state, meta };
    } catch {
      return null;
    }
  }

  async #load(
    id: string,
    projectRoot: string,
    name: string,
    title: string,
    create?: string,
  ): Promise<OpenDoc> {
    const dir = this.docDir(projectRoot, name);
    const file = `${dir}${sep}${AIBDOC}`;
    let live: LiveDoc;
    let meta: CacheMeta | null = null;
    let ids = new IdMap();
    const mirrors = new Map<string, PageMirror>();
    let aib: OpenDoc['aib'] = { text: '', doc: null, rev: 0 };
    let dirty = false;
    let docTitle = title;
    const legacyFiles: string[] = [];
    const skipped: SkippedEdit[] = [];
    let rebuilt = false;
    if (create !== undefined) {
      live = new LiveDoc();
      const parsed = parseDoc(create);
      live.replaceAll(alertsToCallouts(nodesOf(parsed)), live.system); // an agent's "> [!WARNING]" quote is a callout
      mirrors.set(live.firstPage, {
        ...emptyMirror(),
        map: adopt(parsed, live.topBlocks()),
        order: live.topIds(),
        tail: parsed.blocks.length ? parsed.tail : parsed.eol,
        eol: parsed.eol,
      });
      dirty = true;
    } else {
      const text = await readText(file);
      const cache = await this.#readCache(id);
      if (text !== null) {
        const hash = await hashText(text);
        let parsed: AibDoc | null = null;
        let problem: DocRefusal | null = null;
        try {
          parsed = parseAib(text);
          if (cache?.meta.aibHash !== hash) for (const p of parsed.pages) pageNodes(p);
        } catch (error) {
          if (!(error instanceof DocRefusal)) throw error;
          problem = error;
        }
        if (cache && (cache.meta.aibHash === hash || problem)) {
          // the file is what the cache was saved from (or it is broken and the cache is all there is)
          meta = cache.meta;
          live = new LiveDoc(cache.state, meta);
          ids = new IdMap(meta.ids);
          for (const [page, m] of Object.entries(meta.mirrors ?? {})) mirrors.set(page, m);
          aib = { text, doc: parsed, rev: meta.aibRev ?? live.rev };
          if (problem) {
            skipped.push({ at: new Date().toISOString(), reason: 'refused', id: AIBDOC, mirror: '', now: '', file: problem.message, source: 'aibdoc' });
            aib.doc = exportAib(live, meta.title ?? title, ids);
            dirty = true;
          }
          docTitle = meta.title ?? parsed?.title ?? title;
        } else {
          if (problem) throw problem;
          // a git pull, a branch switch, a hand edit, another machine: the doc is rebuilt from the file
          meta = cache?.meta ?? null;
          const built = buildFromAib(parsed!, (meta?.rev ?? 0) + 1);
          live = new LiveDoc(built.state, built.meta);
          ids = built.ids;
          aib = { text, doc: parsed, rev: live.rev };
          docTitle = parsed!.title || title;
          rebuilt = true;
          dirty = true;
        }
      } else {
        const legacy = await this.#legacy(projectRoot, name);
        if (!legacy) throw new DocRefusal('no_doc', `No doc named "${name}" in this project.`);
        docTitle = legacy.title;
        const old = legacy.state ? await readOld(legacy.state) : null;
        if (old) {
          meta = old.meta;
          live = new LiveDoc(old.state, old.meta);
          const m = old.meta.mirror;
          mirrors.set(live.firstPage, {
            ...(m && typeof m.text === 'string' && m.map ? m : emptyMirror()),
            path: legacy.md && m ? legacy.md : '',
          });
          legacyFiles.push(legacy.state!);
        } else {
          const mdText = legacy.md ? (await readText(legacy.md)) ?? '' : '';
          const parsed = parseDoc(mdBody(mdText));
          live = new LiveDoc();
          live.replaceAll(nodesOf(parsed), live.system);
          mirrors.set(live.firstPage, {
            text: mdText,
            map: adopt(parsed, live.topBlocks()),
            order: live.topIds(),
            tail: parsed.blocks.length ? parsed.tail : parsed.eol,
            eol: parsed.eol,
            path: legacy.md ?? '',
          });
        }
        if (legacy.md && !legacy.keepMd) legacyFiles.push(legacy.md);
        legacyFiles.push(...await moveLegacyAssets(live, this.#docsDir(projectRoot), dir));
        dirty = true;
      }
    }
    const doc: OpenDoc = {
      id,
      name,
      title: docTitle,
      projectRoot,
      dir,
      file,
      mirrorPath: '',
      live,
      mirrors,
      ids,
      aib,
      skipped,
      lossy: [],
      dirty,
      timer: null,
      busy: Promise.resolve(),
      artifactId: meta?.artifactId ?? null,
      snapRev: meta?.snapRev ?? 0,
      authors: new Set(),
      snapTimer: null,
      note: '',
      chat: typeof meta?.chat === 'string' ? meta.chat : null,
      legacy: legacyFiles,
      agents: new DocAgents(live),
      epoch: `${this.epoch}.${++this.#loads}`,
    };
    doc.agents.onChange = () => this.#touchSave(doc);
    doc.mirrorPath = this.#pagePaths(doc).get(live.firstPage) ?? '';
    if (rebuilt) await this.#adoptCopies(doc);
    live.onChange = (by) => this.#touched(doc, by);
    live.doc.getMap('drawings').observeDeep(() => this.#touched(doc, null)); // shapes: saved and written out like blocks
    live.beforeEdit = (by) => {
      if (doc.authors.size && !(doc.authors.size === 1 && doc.authors.has(by))) this.snapshot(doc);
    };
    this.docs.set(id, doc);
    if (doc.dirty) await this.flush(doc);
    if (doc.legacy.length) {
      // the new files are written: the old layout's files go
      for (const path of doc.legacy.splice(0)) await Deno.remove(path, { recursive: true }).catch(() => {});
    }
    if (!doc.artifactId) this.snapshot(doc, 'created');
    return doc;
  }

  /** After a rebuild from doc.aibdoc: each page's Markdown copy on disk is bound to the new blocks, so its spelling is kept. */
  async #adoptCopies(doc: OpenDoc): Promise<void> {
    const paths = this.#pagePaths(doc);
    doc.mirrors = new Map();
    for (const { id: page } of doc.live.pageList()) {
      const path = paths.get(page)!;
      const text = await readText(path);
      if (text === null) {
        doc.mirrors.set(page, emptyMirror());
        continue;
      }
      const parsed = parseDoc(mdBody(text));
      doc.mirrors.set(page, {
        text,
        map: adopt(parsed, doc.live.topBlocks(page)),
        order: doc.live.topIds(page),
        tail: parsed.tail,
        eol: parsed.eol,
        path,
      });
    }
  }

  get(id: string): OpenDoc | null {
    return this.docs.get(id) ?? null;
  }

  #touched(doc: OpenDoc, by: string | null): void {
    doc.dirty = true;
    if (by) doc.authors.add(by);
    if (doc.timer !== null) clearTimeout(doc.timer);
    const timer = setTimeout(() => {
      doc.timer = null;
      void this.flush(doc).catch(() => {});
    }, this.options.idleMs ?? 1500);
    Deno.unrefTimer(timer);
    doc.timer = timer;
    if (doc.snapTimer !== null) clearTimeout(doc.snapTimer);
    const snap = setTimeout(() => {
      doc.snapTimer = null;
      this.snapshot(doc);
    }, this.options.snapshotIdleMs ?? 10_000);
    Deno.unrefTimer(snap);
    doc.snapTimer = snap;
  }

  /** Each page's Markdown copy: NN-<title slug>.md in page order. */
  #pagePaths(doc: OpenDoc): Map<string, string> {
    const out = new Map<string, string>();
    doc.live.pageList().forEach((p, k) => {
      out.set(p.id, `${doc.dir}${sep}${String(k + 1).padStart(2, '0')}-${slugOf(p.title)}.md`);
    });
    return out;
  }

  /** One page's Markdown as its copy would have it now (without the note line). */
  pageMarkdown(doc: OpenDoc, page?: string): string {
    const p = page ?? doc.live.firstPage;
    const m = doc.mirrors.get(p) ?? emptyMirror();
    return writeDoc(doc.live.topBlocks(p), m.map, m.tail, m.eol).text;
  }

  /**
   * The doc's Markdown (pure; no file is touched): one page as its copy has it; several pages each after a marker line
   * `<!-- aib:page {"id":…,"title":…} -->` (what history keeps, and what restore reads back).
   */
  markdown(doc: OpenDoc): string {
    const pages = doc.live.pageList();
    if (pages.length === 1) return this.pageMarkdown(doc, pages[0].id);
    return pages.map((p) => `<!-- aib:page ${JSON.stringify({ id: p.id, title: p.title })} -->\n\n${this.pageMarkdown(doc, p.id)}`)
      .join('\n');
  }

  /** One at a time per doc: a poll, an idle flush and an agent call never sync the same file edit twice. */
  #serial<T>(doc: OpenDoc, work: () => Promise<T>): Promise<T> {
    const next = doc.busy.then(work, work);
    doc.busy = next.catch(() => {});
    return next;
  }

  /** Take in edits made to the doc's files, then write them all from the doc. */
  flush(doc: OpenDoc): Promise<void> {
    if (doc.timer !== null) clearTimeout(doc.timer), doc.timer = null;
    return this.#serial(doc, async () => {
      await this.#sync(doc);
      await this.#write(doc);
    });
  }

  async #write(doc: OpenDoc): Promise<void> {
    await Deno.mkdir(doc.dir, { recursive: true });
    fixChartIds(doc.live); // before the copies link their pictures
    const paths = this.#pagePaths(doc);
    const lossy: string[] = [];
    const old: string[] = [];
    for (const { id: page } of doc.live.pageList()) {
      const m = doc.mirrors.get(page) ?? emptyMirror();
      const w = writeDoc(doc.live.topBlocks(page), m.map, m.tail, m.eol);
      lossy.push(...w.lossy);
      const path = paths.get(page)!;
      const text = MD_NOTE + m.eol + m.eol + w.text;
      const onDisk = await readText(path);
      if (text !== onDisk) {
        await writeAtomic(path, text);
        doc.dirty = true;
      }
      if (text !== m.text || path !== m.path) doc.dirty = true;
      if (m.path && m.path !== path) old.push(m.path);
      doc.mirrors.set(page, { ...m, text, map: w.map, order: doc.live.topIds(page), path });
    }
    for (const [page, m] of [...doc.mirrors]) {
      if (paths.has(page)) continue;
      if (m.path) old.push(m.path); // a deleted page's copy
      doc.mirrors.delete(page);
      doc.dirty = true;
    }
    doc.lossy = lossy;
    doc.mirrorPath = paths.get(doc.live.firstPage) ?? doc.mirrorPath;
    await syncDrawings(doc);
    await syncCharts(doc);
    const aib = exportAib(doc.live, doc.title, doc.ids);
    const text = stringifyAib(aib);
    if (text !== doc.aib.text || (await readText(doc.file)) !== text) {
      await writeAtomic(doc.file, text);
      doc.dirty = true;
    }
    doc.aib = { text, doc: aib, rev: doc.live.rev };
    // renamed, moved or deleted pages: their old copies go, now that the new ones are written (never a file a page writes now)
    const now = new Set([...paths.values()].map(pathKey));
    for (const path of old) {
      if (!now.has(pathKey(path))) await Deno.remove(path).catch(() => {});
    }
    if (!doc.dirty) return;
    doc.dirty = false;
    await this.#saveState(doc);
  }

  async #saveState(doc: OpenDoc): Promise<void> {
    const dir = this.#cacheDir(doc.id);
    await Deno.mkdir(dir, { recursive: true });
    await writeAtomic(`${dir}${sep}doc.bin`, doc.live.encode());
    const meta: CacheMeta = {
      ...doc.live.meta(),
      name: doc.name,
      title: doc.title,
      projectRoot: doc.projectRoot,
      aibHash: doc.aib.text ? await hashText(doc.aib.text) : undefined,
      aibRev: doc.aib.rev,
      mirrors: Object.fromEntries(doc.mirrors),
      ids: doc.ids.toJSON((id) => doc.live.has(id)),
      artifactId: doc.artifactId,
      snapRev: doc.snapRev,
      chat: doc.chat,
    };
    await writeAtomic(`${dir}${sep}meta.json`, JSON.stringify(meta));
  }

  /**
   * Take in edits made to the doc's files: drawings, doc.aibdoc, then each page's Markdown copy. Each changed block is applied on its
   * own, guarded by "the doc still has this block as AIB last wrote it"; a block that changed in the doc since (the user typed in
   * it) is skipped and recorded in doc.skipped. Returns what was skipped this time.
   */
  syncMirror(doc: OpenDoc): Promise<SkippedEdit[]> {
    return this.#serial(doc, () => this.#sync(doc));
  }

  async #sync(doc: OpenDoc): Promise<SkippedEdit[]> {
    await syncDrawings(doc); // drawings first: their file edits are taken in before anything writes their files
    const skipped: SkippedEdit[] = [];
    let changed = false;
    const aibText = await readText(doc.file);
    if (aibText !== null && doc.aib.text && aibText !== doc.aib.text && doc.aib.doc) {
      skipped.push(...this.#mergeAib(doc, aibText));
      changed = true;
      // the copies came with that change (a pull brings both): they are bound to the doc as it now stands, not applied again
      for (const { id: page } of doc.live.pageList()) {
        const m = doc.mirrors.get(page);
        const text = m?.path ? await readText(m.path) : null;
        if (!m || text === null || text === m.text) continue;
        const parsed = parseDoc(mdBody(text));
        doc.mirrors.set(page, {
          text,
          map: adopt(parsed, doc.live.topBlocks(page)),
          order: doc.live.topIds(page),
          tail: parsed.tail,
          eol: parsed.eol,
          path: m.path,
        });
      }
    }
    for (const { id: page } of doc.live.pageList()) {
      const m = doc.mirrors.get(page);
      if (!m?.path) continue;
      const text = await readText(m.path);
      if (text === null || text === m.text || !m.order.length) continue;
      const before = m.order.map((id) => ({ id, raw: lf(m.map[id]?.raw ?? ''), sig: m.map[id]?.sig ?? '' }));
      const parsed = parseDoc(mdBody(text));
      const after = parsed.blocks.map((b) => lf(b.raw));
      skipped.push(...this.#applyBlocks(doc, page, before, after, nodesOf(parsed), 'md'));
      // the file's own spelling of every block that now matches the doc is kept; skipped edits are written back from the doc
      doc.mirrors.set(page, {
        text,
        map: adopt(parsed, doc.live.topBlocks(page)),
        order: doc.live.topIds(page),
        tail: parsed.tail,
        eol: parsed.eol,
        path: m.path,
      });
      changed = true;
    }
    doc.skipped.push(...skipped);
    if (doc.skipped.length > 50) doc.skipped.splice(0, doc.skipped.length - 50);
    if (changed) {
      doc.dirty = true;
      await this.#write(doc);
    }
    return skipped;
  }

  /**
   * Apply one page's file edit block by block: `before` is the page as AIB last wrote it (id, the block's text there, its content
   * signature then), `after` the file's blocks now. Changed blocks pair up (align), each applied only if the doc still has it as it
   * was written; otherwise it is skipped.
   */
  #applyBlocks(
    doc: OpenDoc,
    page: string,
    before: { id: string; raw: string; sig: string }[],
    after: string[],
    nodes: PMJson[],
    source: 'md' | 'aibdoc',
  ): SkippedEdit[] {
    const live = doc.live;
    const origin: Origin = live.originFor('file', 'file edit');
    const skipped: SkippedEdit[] = [];
    const current = (id: string): DocBlock | undefined => live.topBlocks(page).find((b) => b.id === id);
    const readable = (s: string) => (source === 'md' ? s : jsonMarkdown(s));
    const skip = (reason: SkippedEdit['reason'], id: string, mirror: string, file: string) => {
      skipped.push({
        ...(reason === 'rich_block' ? { note: RICH_NOTE } : {}),
        at: new Date().toISOString(),
        reason,
        id,
        mirror: readable(mirror),
        now: live.has(id) ? live.markdownOf(id) : '',
        file: readable(file),
        page,
        source,
      });
    };
    let anchor: string | null = null; // the doc block the next inserted block goes after
    for (const pair of align(before.map((b) => b.raw), after)) {
      if (pair.kind === 'same') {
        if (live.has(before[pair.a!].id)) anchor = before[pair.a!].id;
        continue;
      }
      try {
        if (pair.kind === 'insert') {
          const op: Op = anchor && live.has(anchor)
            ? { op: 'insert', target: { kind: 'blocks', ids: [anchor] }, side: 'after', source: blocksSource(nodes[pair.b!]) }
            : { op: 'insert', target: { kind: 'root' }, side: anchor ? 'end' : 'start', source: blocksSource(nodes[pair.b!]) };
          const ack = live.edit([op], origin, page) as { created?: string[] };
          anchor = ack.created?.at(-1) ?? anchor;
          continue;
        }
        const old = before[pair.a!];
        const now = live.has(old.id) && live.pageOf(old.id) === page ? current(old.id) : undefined;
        const wanted = pair.kind === 'delete' ? '' : after[pair.b!];
        if (source === 'md' && now && richOf(now.node)) {
          // its Markdown is a fallback: taking the edit in would drop the callout, the colours, the merged cells
          skip('rich_block', old.id, old.raw, wanted);
          anchor = old.id;
          continue;
        }
        if (!now || sigOf(now.node) !== old.sig) {
          skip(now ? 'user_changed' : 'block_gone', old.id, old.raw, wanted);
          if (now) anchor = old.id;
          continue;
        }
        if (pair.kind === 'delete') {
          if (live.topIds(page).length > 1) live.edit([{ op: 'delete', target: { kind: 'blocks', ids: [old.id] }, force: true }], origin, page);
          continue;
        }
        const ack = live.edit(
          [{ op: 'replace', target: { kind: 'blocks', ids: [old.id] }, force: true, with: blocksSource(nodes[pair.b!]) }],
          origin,
          page,
        ) as { created?: string[] };
        anchor = live.has(old.id) ? old.id : ack.created?.at(-1) ?? anchor;
      } catch (error) {
        if (!(error instanceof DocRefusal)) throw error;
        skip(
          'refused',
          pair.a !== undefined ? before[pair.a].id : '',
          pair.a !== undefined ? before[pair.a].raw : '',
          pair.b !== undefined ? after[pair.b] : '',
        );
      }
    }
    return skipped;
  }

  /**
   * doc.aibdoc changed on disk while the doc is open (a git pull, a hand edit): compare it with what AIB last wrote and take in what
   * changed there. Pages added, renamed, moved and deleted, then each page's blocks, on the guarded path of #applyBlocks: whatever
   * the user changed in the doc since that write is skipped, never overwritten. Comments and drawings in the file are not merged
   * (the doc's stand); the file is then written again from the doc.
   */
  #mergeAib(doc: OpenDoc, text: string): SkippedEdit[] {
    const live = doc.live;
    const origin = live.originFor('file', 'file edit');
    const skipped: SkippedEdit[] = [];
    const note = (reason: SkippedEdit['reason'], id: string, message: string, page?: string) =>
      skipped.push({ at: new Date().toISOString(), reason, id, mirror: '', now: '', file: message, source: 'aibdoc', ...(page ? { page } : {}) });
    let next: AibDoc;
    try {
      next = parseAib(text);
      for (const p of next.pages) pageNodes(p);
    } catch (error) {
      if (!(error instanceof DocRefusal)) throw error;
      note('refused', AIBDOC, error.message);
      doc.aib = { ...doc.aib, text };
      return skipped;
    }
    const last = doc.aib.doc!;
    const lastPages = new Map(last.pages.map((p) => [p.id, p]));
    const nextIds = new Set(next.pages.map((p) => p.id));
    const livePages = () => new Map(live.pageList().map((p) => [p.id, p]));
    // pages the file deleted: only when nothing on them changed since AIB wrote the file
    for (const p of last.pages) {
      if (nextIds.has(p.id) || !livePages().has(p.id)) continue;
      try {
        live.deletePage(p.id, origin, { ifRev: doc.aib.rev, allowUserContent: true, allowDetach: true });
      } catch (error) {
        if (!(error instanceof DocRefusal)) throw error;
        note(error.code === 'guard_mismatch' ? 'user_changed' : 'refused', p.id, `the page was deleted in doc.aibdoc: ${error.message}`, p.id);
      }
    }
    // pages the file added
    let prev: string | null = null;
    for (const p of next.pages) {
      if (!lastPages.has(p.id) && !livePages().has(p.id)) {
        try {
          const ack = live.addPage(p.title, origin, { after: prev ?? undefined, nodes: pageNodes(p), id: p.id });
          prev = ack.page as string;
        } catch (error) {
          if (!(error instanceof DocRefusal)) throw error;
          note('refused', p.id, `a page added in doc.aibdoc: ${error.message}`);
        }
        continue;
      }
      if (livePages().has(p.id)) prev = p.id;
    }
    // renames: only when the doc still has the title the file had
    for (const p of next.pages) {
      const was = lastPages.get(p.id), now = livePages().get(p.id);
      if (!was || !now || was.title === p.title) continue;
      if (now.title !== was.title) {
        note('user_changed', p.id, `renamed to "${p.title}" in doc.aibdoc; the page was renamed in AIB since ("${now.title}")`, p.id);
        continue;
      }
      try {
        live.renamePage(p.id, p.title, origin);
      } catch (error) {
        if (!(error instanceof DocRefusal)) throw error;
        note('refused', p.id, error.message, p.id);
      }
    }
    // order: when the doc's pages still stand in the order the file had
    const common = (ids: string[]) => ids.filter((id) => lastPages.has(id) && nextIds.has(id) && livePages().has(id));
    const lastOrder = common(last.pages.map((p) => p.id)), nextOrder = common(next.pages.map((p) => p.id));
    if (lastOrder.join() !== nextOrder.join()) {
      if (common(live.pageList().map((p) => p.id)).join() === lastOrder.join()) {
        let after: string | null = null;
        for (const p of next.pages) {
          if (!livePages().has(p.id)) continue;
          live.movePage(p.id, after, origin);
          after = p.id;
        }
      } else note('user_changed', AIBDOC, 'pages were reordered in doc.aibdoc; they were reordered in AIB since');
    }
    // blocks, page by page
    for (const p of next.pages) {
      const was = lastPages.get(p.id);
      if (!was || !livePages().has(p.id)) continue;
      const before = was.content.map((n) => {
        const node = stripIds(n);
        return { id: doc.ids.liveOf(String(n.id ?? '')), raw: blockKey(node), sig: sigOf(node) };
      });
      const nodes = pageNodes(p);
      skipped.push(...this.#applyBlocks(doc, p.id, before, nodes.map(blockKey), nodes, 'aibdoc'));
    }
    if (next.title && next.title !== last.title && doc.title === last.title) doc.title = next.title;
    doc.aib = { ...doc.aib, text };
    return skipped;
  }

  // ---------- pages ----------

  /**
   * Add, rename, move or delete a page (agent tools; LiveDoc guards them). The copies follow on the next write. An agent's delete that
   * passes its guards becomes a request the user answers (decideRequest); an agent's rename is refused over a newer user rename.
   */
  pageOp(doc: OpenDoc, action: unknown, args: Record<string, unknown>, origin: Origin): Record<string, unknown> {
    const live = doc.live;
    switch (action) {
      case 'add':
        return live.addPage(args.title, origin, { after: args.after, markdown: args.markdown });
      case 'rename':
        return live.renamePage(args.page, args.title, origin, args.ifRev, doc.agents.seen.get(origin.name) ?? 0);
      case 'move':
        return live.movePage(args.page, args.after, origin);
      case 'delete': {
        const opts = { ifRev: args.ifRev, allowUserContent: args.allowUserContent, allowDetach: args.allowDetach };
        if (origin.kind !== 'agent') return live.deletePage(args.page, origin, opts);
        const ok = live.deletePage(args.page, origin, { ...opts, check: true });
        const request = doc.agents.requestDelete(origin.name, ok.page as string, ok.title as string);
        return {
          ok: true,
          pending: true,
          rev: live.rev,
          page: request.page,
          note: `Not deleted yet: the user sees your request to delete "${request.title}" and answers Delete or Keep. A later doc tool ` +
            'result tells you which.',
        };
      }
      default:
        throw new DocRefusal('bad_op', '`action` is add, rename, move or delete');
    }
  }

  /**
   * The user's page operations (the page's route, user origin): add {title, after?}, rename {page, title}, move {page, index} (by
   * place: the page's map stays), duplicate {page, title?}, delete {page} (a history snapshot first; no guards: the user decides).
   */
  userPageOp(doc: OpenDoc, action: unknown, args: Record<string, unknown>): Record<string, unknown> {
    const live = doc.live;
    const user = live.user;
    switch (action) {
      case 'add':
        return live.addPage(args.title, user, { after: args.after });
      case 'rename':
        return live.renamePage(args.page, args.title, user);
      case 'move': {
        const page = live.resolvePage(args.page);
        const rest = live.pageList().filter((p) => p.id !== page);
        const index = Number(args.index);
        if (!Number.isInteger(index) || index < 0 || index > rest.length) {
          throw new DocRefusal('bad_op', `"index" is the page's new place: 0-${rest.length}`);
        }
        return live.movePage(page, index === 0 ? null : rest[index - 1].id, user);
      }
      case 'duplicate': {
        const page = live.resolvePage(args.page);
        const from = live.pageList().find((p) => p.id === page)!;
        let title = typeof args.title === 'string' && args.title.trim() ? args.title : `${from.title} (copy)`;
        for (let k = 2; live.pageList().some((p) => p.title.toLowerCase() === title.toLowerCase()); k++) {
          title = `${from.title} (copy ${k})`;
        }
        const nodes = live.topBlocks(page).map((b) => withoutAgentMarks(b.node));
        return live.addPage(title.slice(0, 100), user, { after: page, nodes });
      }
      case 'delete': {
        const page = live.resolvePage(args.page);
        this.snapshot(doc, 'before a page was deleted');
        const done = live.deletePage(page, user, { ifRev: live.rev, allowUserContent: true, allowDetach: true });
        for (const r of doc.agents.dropRequests(page)) {
          doc.agents.notice(r.chat, `The user deleted page "${r.title}" (it is in the doc's history).`);
        }
        return done;
      }
      default:
        throw new DocRefusal('bad_op', '`action` is add, rename, move, duplicate or delete');
    }
  }

  /**
   * The user's answer to an agent's page delete request: "delete" deletes the page as it stands now (a history snapshot first),
   * "keep" drops the request; either way the chat hears it in its next doc tool result.
   */
  decideRequest(doc: OpenDoc, pageValue: unknown, chat: unknown, decision: unknown): Record<string, unknown> {
    const page = typeof pageValue === 'string' ? pageValue : '';
    const requests = doc.agents.requestsFor(page).filter((r) => !chat || r.chat === chat);
    if (!requests.length) throw new DocRefusal('no_request', 'There is no delete request for that page (any more).');
    if (decision === 'delete') return this.userPageOp(doc, 'delete', { page });
    if (decision !== 'keep') throw new DocRefusal('bad_op', '`decision` is delete or keep');
    for (const r of doc.agents.dropRequests(page, typeof chat === 'string' && chat ? chat : undefined)) {
      doc.agents.notice(r.chat, `The user kept page "${r.title}": do not delete it.`);
    }
    return { ok: true, kept: page, rev: doc.live.rev };
  }

  /**
   * A chat's turn ended (or was cancelled, or its connection went): in every open doc it stops showing, its claim goes, its refused
   * edits still undone become notes for the page; a doc it changed gets a history version, announced to the page.
   */
  turnEnded(chat: string): void {
    for (const doc of this.docs.values()) {
      const active = doc.agents.active().includes(chat);
      doc.agents.turnEnded(chat);
      if (!active && !doc.authors.has(chat)) continue;
      const n = this.snapshot(doc, `${agentName(chat)}'s turn`);
      if (n !== null) doc.live.sendControl({ type: 'history', version: n, by: authorNames(chat), rev: doc.live.rev });
    }
  }

  // ---------- history ----------

  /** Snapshot the doc into its history artifact now (if it changed since the last one). Returns the version number or null. */
  snapshot(doc: OpenDoc, note = ''): number | null {
    const history = this.options.history;
    if (!history || (doc.snapRev === doc.live.rev && doc.artifactId)) return null;
    if (doc.snapTimer !== null) clearTimeout(doc.snapTimer), doc.snapTimer = null;
    const by = [...doc.authors].sort().join('+') || (note === 'created' ? 'system' : 'user');
    const text = stringifyAib(exportAib(doc.live, doc.title, doc.ids));
    const n = history.snapshot(doc, text, by, `rev ${doc.live.rev}${note || doc.note ? '; ' + (note || doc.note) : ''}`, 'json');
    doc.snapRev = doc.live.rev;
    doc.authors.clear();
    doc.note = '';
    doc.dirty = true;
    return n;
  }

  history(doc: OpenDoc): { latest: number; versions: unknown[] } {
    return { latest: doc.live.rev, versions: this.options.history?.list(doc) ?? [] };
  }

  /** A version as stored: a doc.aibdoc (JSON), or Markdown for versions from before that. */
  versionText(doc: OpenDoc, n: number): string {
    const text = this.options.history?.read(doc, n);
    if (text === null || text === undefined) {
      throw new DocRefusal('no_version', `There is no version ${n} of this doc; doc_history lists them.`);
    }
    return text;
  }

  /** A version as Markdown (for reading): pages marked as in markdown() when there are several. */
  readVersion(doc: OpenDoc, n: number): string {
    const text = this.versionText(doc, n);
    const aib = versionAib(text);
    if (!aib) return text;
    const built = buildFromAib(aib, 0);
    const tmp = new LiveDoc(built.state, built.meta);
    try {
      const md = (p: string) => writeDoc(tmp.topBlocks(p), {}, '\n', '\n').text;
      const pages = tmp.pageList();
      if (pages.length === 1) return md(pages[0].id);
      return pages.map((p) => `<!-- aib:page ${JSON.stringify({ id: p.id, title: p.title })} -->\n\n${md(p.id)}`).join('\n');
    } finally {
      tmp.destroy();
    }
  }

  /**
   * Restore the doc to a history version, only when nothing changed since the caller's read (`ifRev` = the latest rev). Its pages
   * read exactly as that version did; a version from before pages restores the first page and drops the others. With `page` (an id
   * or title of a page in that version) only that page comes back, the others stay as they are.
   * A doc.aibdoc version comes back exactly: rich blocks, marks, block ids in the file, its drawings, and its comment threads
   * (threads made since stay; a thread that exists keeps its replies and only takes the version's anchor if its own words are gone).
   */
  async restore(
    doc: OpenDoc,
    n: number,
    ifRev: unknown,
    origin: Origin,
    pageValue?: unknown,
  ): Promise<{ rev: number; restored: number; page?: string }> {
    if (typeof ifRev !== 'number') {
      throw new DocRefusal('missing_guard', 'restore needs "ifRev" = the latest rev (doc_history shows it as `latest`).');
    }
    if (ifRev !== doc.live.rev) {
      throw new DocRefusal(
        'guard_mismatch',
        `The doc changed since (rev ${doc.live.rev}, you gave ${ifRev}): restore only rewinds when nothing changed since your read. ` +
          'Look at doc_history again, or bring back just the words you need with an ordinary insert.',
        { rev: doc.live.rev },
      );
    }
    const text = this.versionText(doc, n);
    const aib = versionAib(text);
    const one = pageValue !== undefined && pageValue !== null && pageValue !== '';
    let restoredPage: string | undefined;
    await this.#serial(doc, async () => {
      await this.#sync(doc);
      if (doc.live.rev !== ifRev) throw new DocRefusal('guard_mismatch', 'The doc changed while restoring; nothing was restored.');
      const first = doc.live.pageList()[0];
      const listed = aib ? aib.pages.map((p) => ({ id: p.id, title: p.title })) : splitPages(text, first);
      const want = one ? versionPage(doc.live, listed, pageValue, n) : null;
      this.snapshot(doc);
      if (aib) {
        const restored = want ? aib.pages.filter((p) => p.id === want.id) : aib.pages;
        const nodes = restored.map((p) => pageNodes(p));
        const at: string[] = [];
        if (want) at.push(this.#restorePage(doc, listed, want, nodes[0], origin));
        else {
          doc.live.setPages(restored.map((p, k) => ({ id: p.id, title: p.title, nodes: nodes[k] })), origin);
          at.push(...restored.map((p) => p.id));
        }
        const byFile = new Map();
        restored.forEach((p, k) => bindIds(p.content, doc.live.fragOf(at[k]), doc.ids, byFile));
        doc.live.doc.transact(() => {
          restoreThreads(doc.live.doc, aib.comments.filter((t) => !want || t.page === want.id), byFile);
          restoreDrawings(doc.live.doc, aib.drawings.filter((d) => !want || d.page === want.id));
        }, origin);
        restoredPage = want ? at[0] : undefined;
        doc.note = want ? `restored page "${want.title}" from v${n}` : `restored v${n}`;
        await this.#write(doc);
        return;
      }
      const pages = want ? splitPages(text, first).filter((p) => p.id === want.id) : splitPages(text, first);
      const parsed = pages.map((p) => parseDoc(p.text));
      if (want) {
        const id = this.#restorePage(doc, listed, want, nodesOf(parsed[0]), origin);
        pages[0] = { ...pages[0], id };
        restoredPage = id;
      } else doc.live.setPages(pages.map((p, k) => ({ id: p.id, title: p.title, nodes: nodesOf(parsed[k]) })), origin);
      pages.forEach((p, k) => {
        const m = doc.mirrors.get(p.id) ?? emptyMirror();
        doc.mirrors.set(p.id, {
          ...m,
          map: adopt(parsed[k], doc.live.topBlocks(p.id)),
          order: doc.live.topIds(p.id),
          tail: parsed[k].tail,
          eol: parsed[k].eol,
        });
      });
      doc.note = want ? `restored page "${want.title}" from v${n}` : `restored v${n}`;
      await this.#write(doc);
    });
    return { rev: doc.live.rev, restored: n, ...(restoredPage ? { page: restoredPage } : {}) };
  }

  /**
   * One page back from a version: its content (and title, unless another page has it now); a page deleted since comes back where
   * it stood (after the page before it in that version). Returns the page's id now.
   */
  #restorePage(
    doc: OpenDoc,
    listed: { id: string; title: string }[],
    want: { id: string; title: string },
    nodes: PMJson[],
    origin: Origin,
  ): string {
    const live = doc.live;
    const taken = (title: string, except: string) =>
      live.pageList().some((p) => p.id !== except && p.title.toLowerCase() === title.toLowerCase());
    if (live.pageList().some((p) => p.id === want.id)) {
      live.replaceAll(nodes, origin, want.id);
      const now = live.pageList().find((p) => p.id === want.id)!;
      if (now.title !== want.title && !taken(want.title, want.id)) live.renamePage(want.id, want.title, origin);
      return want.id;
    }
    const index = listed.findIndex((p) => p.id === want.id);
    const before = listed.slice(0, index).reverse().find((p) => live.pageList().some((x) => x.id === p.id));
    const title = taken(want.title, '') ? `${want.title} (restored)`.slice(0, 100) : want.title;
    const id = live.addPage(title, live.system, { after: before?.id, nodes: [{ type: 'paragraph' }], id: want.id }).page as string;
    if (!before) live.movePage(id, null, live.system);
    live.replaceAll(nodes, origin, id);
    return id;
  }

  /**
   * Link the doc to a chat (its lasting id). `replace`: the page opened it from this chat; otherwise only a doc without a link takes
   * it (an agent's first tool call on it).
   */
  link(doc: OpenDoc, chat: string, replace: boolean): void {
    if (!chat || doc.chat === chat || (doc.chat && !replace)) return;
    doc.chat = chat;
    doc.dirty = true;
    this.#touchSave(doc);
  }

  #touchSave(doc: OpenDoc): void {
    if (doc.timer !== null) clearTimeout(doc.timer);
    const timer = setTimeout(() => {
      doc.timer = null;
      void this.flush(doc).catch(() => {});
    }, this.options.idleMs ?? 1500);
    Deno.unrefTimer(timer);
    doc.timer = timer;
  }

  /**
   * What the UI can show about a doc: where it is, its pages (each with its Markdown copy), its rev, skipped file edits, lossy
   * blocks, its linked chat and its comment threads (with `seq`, the latest comment change).
   */
  info(doc: OpenDoc): Record<string, unknown> {
    const comments = doc.live.comments.list();
    const paths = this.#pagePaths(doc);
    return {
      doc: doc.id,
      name: doc.name,
      title: doc.title,
      dir: doc.dir,
      file: doc.file,
      pages: doc.live.pages().map((p) => ({ ...p, md: paths.get(p.id) })),
      rev: doc.live.rev,
      blocks: doc.live.blockCount,
      skipped: doc.skipped,
      lossy: doc.lossy,
      artifactId: doc.artifactId,
      chat: doc.chat,
      commentSeq: comments.seq,
      comments: comments.threads,
      epoch: doc.epoch,
      ...doc.agents.state(),
    };
  }

  /** info() plus the files the doc owns (the Files view, Ctrl+K, Changes and Merge hide exactly these). */
  async infoWithOwned(doc: OpenDoc): Promise<Record<string, unknown>> {
    return { ...this.info(doc), ...(await ownedPaths(doc.projectRoot, doc.dir, [...this.#pagePaths(doc).values()])) };
  }

  async close(): Promise<void> {
    if (this.#poll !== null) clearInterval(this.#poll), this.#poll = null;
    for (const doc of this.docs.values()) {
      await this.flush(doc).catch(() => {});
      this.snapshot(doc);
      if (doc.snapTimer !== null) clearTimeout(doc.snapTimer);
      await this.#saveState(doc).catch(() => {});
      doc.agents.destroy();
      doc.live.destroy();
    }
    this.docs.clear();
  }
}

/** The page of a version that `value` names: its id or title there, or the id of the live page with that title. */
function versionPage(live: LiveDoc, listed: { id: string; title: string }[], value: unknown, n: number): { id: string; title: string } {
  const v = String(value).trim();
  const hit = listed.find((p) => p.id === v) ?? listed.find((p) => p.title.toLowerCase() === v.toLowerCase());
  if (hit) return hit;
  try {
    const id = live.resolvePage(v);
    const byLive = listed.find((p) => p.id === id);
    if (byLive) return byLive;
  } catch { /* not a live page either */ }
  throw new DocRefusal(
    'no_page',
    `Version ${n} has no page ${JSON.stringify(value)}. Its pages: ${listed.map((p) => `${p.id} ("${p.title}")`).join(', ')}.`,
  );
}

/** History text back into pages: marker lines split it; text without markers is the first page alone. */
function splitPages(text: string, first: { id: string; title: string }): { id: string; title: string; text: string }[] {
  const lines = text.split(/(?<=\n)/);
  const out: { id: string; title: string; text: string }[] = [];
  for (const line of lines) {
    const m = PAGE_MARK.exec(line.replace(/\r?\n$/, ''));
    let mark: { id?: unknown; title?: unknown } | null = null;
    if (m) {
      try {
        mark = JSON.parse(m[1]);
      } catch { /* not a marker */ }
    }
    if (mark && typeof mark.id === 'string' && typeof mark.title === 'string') {
      out.push({ id: mark.id, title: mark.title, text: '' });
      continue;
    }
    if (!out.length) out.push({ id: first.id, title: first.title, text: '' });
    out[out.length - 1].text += line;
  }
  if (!out.length) out.push({ id: first.id, title: first.title, text: '' });
  // the blank line after each marker and the newline that joined pages are the marker's, not the page's
  return out.map((p, k) => ({ ...p, text: (text.startsWith('<!-- aib:page') || k > 0 ? p.text.replace(/^\r?\n/, '') : p.text) }))
    .map((p, k, all) => ({ ...p, text: k < all.length - 1 ? p.text.replace(/\r?\n$/, '') : p.text }));
}

