export async function docId(
  projectRoot: string,
  name: string,
): Promise<string> {
  const key = (Deno.build.os === 'windows' ? projectRoot.toLowerCase() : projectRoot) + '\n' + name;
  const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(key)));
  return [...digest.slice(0, 8)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

/** A file name from a title: lowercase ASCII words joined by hyphens, at most `max` characters. */
export function slugOf(text: string, max = 50, empty = 'page'): string {
  const s = text.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  let cut = s.slice(0, max);
  if (s.length > max && s[max] !== '-' && cut.lastIndexOf('-') > max / 2) cut = cut.slice(0, cut.lastIndexOf('-')); // whole words
  return cut.replace(/-+$/, '') || empty;
}

/** The doc from what an agent or the page gave: "plan", "My Plan", "docs/plan", "docs/plan/doc.aibdoc" or the old "docs/plan.md". */
export function docRef(value: unknown): { name: string; title: string } {
  if (typeof value !== 'string') throw new DocRefusal('bad_doc', '`doc` must be the doc\'s name, e.g. "plan" (its folder is docs/plan/)');
  let name = value.trim().replace(/\\/g, '/');
  if (name.startsWith('docs/')) name = name.slice(5);
  name = name.replace(/\/(?:doc\.aibdoc|\d{2,}-[^/]*\.md|assets(?:\/.*)?)$/i, '').replace(/\/+$/, '');
  if (name.toLowerCase().endsWith('.md')) name = name.slice(0, -3);
  if (!NAME.test(name) || name.endsWith('.')) {
    throw new DocRefusal('bad_doc', '`doc` must be a plain name (letters, digits, space, . _ -), e.g. "plan"; its folder is docs/<name>/');
  }
  return { name: slugOf(name, 60, 'doc'), title: name };
}

/** The doc's folder name. */
export function docName(value: unknown): string {
  return docRef(value).name;
}

/** Blocks of a parsed file as doc nodes; a block the schema can't hold stays verbatim as a raw block. */
function nodesOf(parsed: ParsedDoc): PMJson[] {
  return parsed.blocks.map((b) => {
    try {
      const node = schema.nodeFromJSON(b.node);
      node.check();
      return b.node;
    } catch {
      return { type: 'rawBlock', attrs: { kind: 'other', text: b.raw.replace(/\r\n?/g, '\n') } };
    }
  });
}

/** A Markdown copy's text without AIB's note line. */
export function mdBody(text: string): string {
  return text.replace(NOTE_LINE, '');
}

