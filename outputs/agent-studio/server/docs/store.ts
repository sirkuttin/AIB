/**
 * A doc of the old layout: its drawing blocks point at <name>.assets/; they now point at assets/ in the doc's folder, and the files
 * are copied there. Returns the old folders, to remove once the new files are written.
 */
async function moveLegacyAssets(live: LiveDoc, docsDir: string, dir: string): Promise<string[]> {
  const olds = new Set<string>();
  const els: Y.XmlElement[] = [];
  const walk = (p: Y.XmlFragment | Y.XmlElement) => {
    for (const c of p.toArray()) {
      if (!(c instanceof Y.XmlElement)) continue;
      if (c.nodeName === 'drawing') {
        const m = LEGACY_DRAWING_SRC.exec(String(c.getAttribute('src') ?? ''));
        if (m) {
          olds.add(m[1]);
          els.push(c);
        }
      } else walk(c);
    }
  };
  for (const { frag } of live.pageFrags()) walk(frag);
  if (!els.length) return [];
  live.doc.transact(() => {
    for (const el of els) {
      const m = LEGACY_DRAWING_SRC.exec(String(el.getAttribute('src')))!;
      el.setAttribute('src', `assets/${m[2]}.excalidraw.svg`);
    }
  }, live.system);
  const out: string[] = [];
  for (const name of olds) {
    const from = `${docsDir}${sep}${name}.assets`;
    try {
      await Deno.mkdir(`${dir}${sep}assets`, { recursive: true });
      for await (const e of Deno.readDir(from)) {
        if (e.isFile) await Deno.copyFile(`${from}${sep}${e.name}`, `${dir}${sep}assets${sep}${e.name}`);
      }
      out.push(from);
    } catch { /* no such folder */ }
  }
  return out;
}

