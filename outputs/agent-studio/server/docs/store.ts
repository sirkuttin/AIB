/**
 * The open local docs, their files in the project, their cache and their history.
 *
 *   The doc  <project>/docs/<doc>/doc.aibdoc (aibdoc.ts): readable JSON with the pages, blocks, comments, drawings and agent marks,
 *            meant to be committed. Written on idle (atomically) and on close. This is the source of truth.
 *   Copies   <project>/docs/<doc>/NN-<page-title>.md, one per page (01, 02, ... in page order), each starting with a one-line note that
 *            AIB writes it. Only blocks that changed are written fresh; every other block keeps its exact original text
 *            (markdown.ts writeDoc), so a git diff shows just the edit. Renaming or moving a page renames its file.
 *            Agents' file tools may edit them: before every write and every agent call (and on a poll) the store compares each file
 *            with what it last wrote, block by block, and applies only the blocks that changed there, each guarded: a block that
 *            changed in the doc since that copy (the user typed in it) is skipped and recorded in `skipped`, never overwritten.
 *   Assets   <project>/docs/<doc>/assets/: drawings (drawing/assets.ts), charts' pictures <chart>.chart.svg (charts.ts).
 *   Cache    <stateDir>/docs/cache/<key>/doc.bin (the Y.Doc) + meta.json (revs, who changed what, the copies' source maps, the hash of
 *            the doc.aibdoc it was saved with). On open the cache is used only when that hash matches the file; otherwise (a git
 *            pull, a branch switch, a hand edit) the doc is rebuilt from doc.aibdoc. A doc.aibdoc changed on disk while the doc is
 *            open is merged in block by block on the same guarded path as the Markdown copies.
 *   History  On idle (and before an agent's edit lands on someone else's), the whole doc.aibdoc (pages, rich blocks, marks, comments,
 *            drawings) is snapshotted as a version of the doc's artifact in AIB's artifact store (history.ts). Restore (the whole doc
 *            or one page) brings it back exactly; older Markdown versions restore from their Markdown.
 *
 * A doc from before pages (docs/<name>.md + state in <stateDir>/docs/<id>/) is moved to docs/<doc>/ with one page on first open; its
 * old files go only after the new ones are written.
 */
