'use strict';
/* Condensed chat views, the pure part: which rows each view shows. No DOM here (views-ui.js draws), so it runs in node tests.
   A chat is cut into groups by isPrompt alone: one group per prompt of yours, holding everything up to your next prompt.
   turn-end rows are never used for grouping (a saved transcript has none), so a live and a saved copy of one session
   give the same groups. project(rows, view, opts) -> {view, units, flat, tail, dropped}:
     unit = {key, prompt, earlier, body}
       prompt   the prompt row, or null for rows before the first prompt (earlier: the prompt is on an older, unloaded page)
       body     what is drawn after the prompt, in order: {row, after?} a message, {fold: {key, rows, counts}} a closed
                "Show steps" line for a run of tool calls, results and thinking between two messages, or
                {line:'stopped'|'working'|'none', text}
     flat   the rows drawn as top-level bubbles, in order (what the "new" marker counts)
     tail   a still-running plan, drawn last (as Full does)
   Prompts is projected differently: unit = {key, prompt, earlier, rows, replies, time, error, working}, every row of the turn in rows.
   opts.live (Chat, with opts.working) puts the live line where the newest run of steps is (in place of its fold), else last:
     body item {line:'working', text, live} where live = {step, n, since, elsewhere, waiting} (see liveStatus).
   "full" is not projected: callers keep using the raw rows. */
(function (root) {
  const VIEWS = ['full', 'chat', 'prompts'];
  const LABELS = { full: 'Full', chat: 'Chat', prompts: 'Prompts' };
  const AVAILABLE = { full: true, chat: true, prompts: true };
  const DEFAULTABLE = ['full', 'chat']; // Prompts is for finding something: a switch-to view, never the default
  const DEFAULT_VIEW = 'full';
  const CAP = 500;

  const streamUI = () => {
    if (root.StreamUI) return root.StreamUI;
    try {
      return typeof module === 'object' && module.require ? module.require('./stream-ui.js') : null;
    } catch {
      return null;
    }
  };
  /* Mirrors monitor.py _BOILERPLATE (minus the bare "[Image]" marker, which only matters for titles). */
  const BOILERPLATE =
    /^\s*(?:this session is being continued from a previous conversation|caveat:\s*the messages below were generated by the user while running local commands|\[request interrupted by user|base directory for this skill:|the user opened the file|<local-command-|continue from where you left off)/i;
  const INTERRUPT = /^\s*\[request interrupted by user/i;
  const hasFiles = (r) => !!(r && r.attachments && r.attachments.length);
  const userText = (r) => {
    const SU = streamUI();
    const v = typeof r.value === 'string' ? r.value : '';
    const shown = SU && SU.stripViewContext ? SU.stripViewContext(v) : v;
    return SU && SU.stripInjected ? SU.stripInjected(shown) : shown; // the words of a turn that also carries reminders
  };

  /* A user row with text or attachments that is something the user said: not an injected note, boilerplate or an interrupt. */
  function isPrompt(row) {
    if (!row || row.role !== 'user') return false;
    if (hasFiles(row)) return true;
    const text = userText(row);
    if (!text || !text.trim()) return false;
    const SU = streamUI();
    if (SU && SU.classifyUser && SU.classifyUser(text)) return false;
    return !BOILERPLATE.test(text);
  }
  const isInterrupt = (r) => !!r && r.role === 'user' && !hasFiles(r) && INTERRUPT.test(userText(r));
  const isCancelled = (r) => !!r && r.role === 'turn-end' && String(r.value) === 'cancelled';
  const isTaskNote = (r) => !!r && r.role === 'user' && /^\s*<task-notification\b/i.test(String(r.value || ''));
  const isToolRow = (r) => r.role === 'tool' || r.role === 'result';
  const failedTool = (r) =>
    (r.role === 'tool' &&
      ((r.call && r.call.result && r.call.result.isError) || (r.raw && r.raw.status === 'failed'))) ||
    (r.role === 'error' && !!r.callId);

  /* time + a hash of the text: the same prompt keeps the same key across renders and new turns. */
  function hash(s) {
    let h = 5381;
    for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0;
    return (h >>> 0).toString(36);
  }
  function promptKey(row) {
    if (!row) return 'head';
    const t = row.time == null ? '' : String(row.time);
    return t + ':' + hash(userText(row) + '|' + ((row.attachments && row.attachments.length) || 0));
  }

  const isRunningPlan = (r) =>
    !!r &&
    r.role === 'plan' &&
    Array.isArray(r.entries) &&
    r.entries.length > 0 &&
    r.entries.some((x) => x.status !== 'completed');
  /* The same test chat.js dockedPlan uses: only the newest plan row, and only while it has work left. */
  function runningPlan(rows) {
    for (let i = rows.length - 1; i >= 0; i--)
      if (rows[i].role === 'plan') return isRunningPlan(rows[i]) ? rows[i] : null;
    return null;
  }

  function split(rows) {
    const units = [];
    let cur = null;
    const seen = new Map();
    for (const row of rows) {
      if (isPrompt(row)) {
        let key = 'p:' + promptKey(row);
        const n = (seen.get(key) || 0) + 1;
        seen.set(key, n);
        if (n > 1) key += '#' + n;
        cur = { key, prompt: row, earlier: false, rows: [] };
        units.push(cur);
      } else {
        if (!cur) {
          cur = { key: 'head', prompt: null, earlier: false, rows: [] };
          units.push(cur);
        }
        cur.rows.push(row);
      }
    }
    return units;
  }

  /* Was the last assistant row written in answer to a background task (the notice came right before it)? */
  function afterBackground(rows, at) {
    for (let i = at - 1; i >= 0; i--) {
      const r = rows[i];
      if (r.role === 'assistant') return false;
      if (isTaskNote(r)) return true;
      if (r.role === 'user' && !isInterrupt(r)) return false;
    }
    return false;
  }

  const isNoticeLike = (r) => r.role === 'notice' || (r.role === 'error' && !r.callId);
  const alerting = (r) => r.role === 'notice' && /^(error|disconnected)$/i.test(String(r.label || ''));
  const pinned = (r) => r.role === 'unknown-send' || (Array.isArray(r.actions) && r.actions.length > 0);

  function counts(steps, partial) {
    const c = { messages: 0, tools: 0, failed: 0, thinking: 0, partial: !!partial };
    for (const r of steps) {
      if (r.role === 'thinking') c.thinking++;
      else if (isToolRow(r) || r.role === 'error') {
        c.tools++;
        if (failedTool(r)) c.failed++;
      } else if (r.role !== 'plan' && r.role !== 'turn-end' && r.role !== 'task-done') c.messages++;
    }
    return c;
  }

  const stopLine = { line: 'stopped', text: 'Stopped' };
  /* Tool calls, their results and thinking: what a "Show steps" line folds. */
  const isStep = (r) => r.role === 'thinking' || isToolRow(r) || (r.role === 'error' && !!r.callId);

  /* Your prompt's turn as a chat: the AI's messages in order; each run of steps between two messages is one closed fold, where
     those rows happened. Never folded: errors and disconnect notices, rows with actions, unknown-send rows, the stop line. Rows that
     are neither messages nor steps (turn ends, finished-task marks, plans that are done, other notices) are not drawn. */
  function chatOf(unit) {
    const rows = unit.rows,
      body = [],
      seen = new Map();
    let run = null,
      stopped = false,
      last = -1;
    for (let i = rows.length - 1; i >= 0 && last < 0; i--) if (rows[i].role === 'assistant') last = i;
    const close = () => {
      if (!run) return;
      let key = 'f:' + String(run[0].time == null ? '' : run[0].time) + '|' + unit.key;
      const n = (seen.get(key) || 0) + 1;
      seen.set(key, n);
      if (n > 1) key += '#' + n;
      body.push({ fold: { key, rows: run, counts: counts(run, unit.earlier) } });
      run = null;
    };
    rows.forEach((r, i) => {
      if (isInterrupt(r) || isCancelled(r)) {
        close();
        if (!stopped) body.push(stopLine);
        stopped = true;
      } else if (isStep(r)) {
        (run = run || []).push(r);
      } else if (r.role === 'assistant') {
        close();
        body.push(i === last ? { row: r, after: afterBackground(rows, i) } : { row: r });
      } else if (r.role === 'nextstep' || alerting(r) || (r.role === 'error' && !r.callId) || pinned(r)) {
        close();
        body.push({ row: r });
      }
    });
    close();
    return { body };
  }

  const size = (u) => 1 + u.body.reduce((n, b) => n + (b.fold ? b.fold.rows.length : 1), 0);

  /* ---- Prompts: one unit per prompt of yours, holding every row up to your next prompt ---- */
  /* A prompt has an error when the agent or the connection failed, or its turn stopped on a failed step. A step that failed
     mid-turn and was followed by the agent's reply is not one: the agent got past it (the fold still says "1 failed"). */
  function hasError(rows) {
    let failedLast = false;
    for (const r of rows) {
      if ((r.role === 'error' && !r.callId) || alerting(r)) return true;
      if (failedTool(r)) failedLast = true;
      else if (r.role === 'assistant' && r.value) failedLast = false;
    }
    return failedLast;
  }
  function promptsOf(rows, opts) {
    const units = split(rows)
      .filter((u) => u.prompt) // rows before the first loaded prompt belong to a prompt on an older page
      .map((u) => ({
        key: u.key,
        prompt: u.prompt,
        earlier: false,
        rows: u.rows,
        replies: u.rows.filter((r) => r.role === 'assistant').length,
        time: u.prompt.time,
        error: hasError(u.rows),
        working: false,
      }));
    if (units.length && opts.working) units[units.length - 1].working = true;
    return { view: 'prompts', units, flat: units.map((u) => u.prompt), tail: null, dropped: 0 };
  }
  /* The prompt's text matches a find-box query (case-insensitive, every word). */
  function promptMatches(row, query) {
    const words = String(query || '')
      .toLowerCase()
      .split(/\s+/)
      .filter(Boolean);
    if (!words.length) return true;
    const text = userText(row).toLowerCase();
    return words.every((w) => text.includes(w));
  }

  /* ---- the live line: what the AI is doing right now, read from RAW events (thinking rows exist only with Show thinking on) ---- */
  function timeMs(t) {
    if (t == null || t === '') return null;
    if (typeof t === 'number') return isFinite(t) ? (t < 1e12 ? t * 1000 : t) : null;
    const v = Date.parse(t);
    return isNaN(v) ? null : v;
  }
  /* "0:42", "12:05", "1:02:03" */
  function clock(ms) {
    const total = Math.max(0, Math.floor((Number(ms) || 0) / 1000)),
      s = total % 60,
      m = Math.floor(total / 60) % 60,
      h = Math.floor(total / 3600);
    return (h ? h + ':' + String(m).padStart(2, '0') : m) + ':' + String(s).padStart(2, '0');
  }
  /* {kind:'tool', label, text, title} for a tool row: the badge ("run") and what it does, as the tool rows show them. */
  function stepOf(row) {
    const TV = root.ToolViews;
    let s = null;
    try {
      s = TV && TV.summarize ? TV.summarize(row) : null;
    } catch {
      s = null;
    }
    const label = s && s.label ? s.label : 'tool',
      text = String((s && s.text) || row.label || '')
        .replace(/^Ran\s+/, '')
        .trim();
    return {
      kind: 'tool',
      label,
      text: text.length > 160 ? text.slice(0, 159) + '…' : text,
      title: (s && s.hint) || text,
    };
  }
  const parseJSON = (v) => {
    try {
      return JSON.parse(String(v || '').replace(/\n\n\[Display shortened[^\]]*\]\s*$/, ''));
    } catch {
      return v;
    }
  };
  /* events: the live event log ({kind:'user'|'update', data, time}) or a saved transcript's events ({kind, label, text, time, ...}).
     -> {step: {kind:'tool', label, text, title} | {kind:'thinking'}, n, since} for the newest prompt, or null when there is none.
     step: the newest tool call or thinking chunk after that prompt. n: the step number (tool calls so far, plus the thinking now).
     since: the prompt's time in ms, so the clock survives a Studio restart. */
  function liveStatus(events, source, sessionId) {
    if (!Array.isArray(events)) return null;
    const live = source !== 'saved',
      other = (e) => !!(sessionId && e.data && e.data.sessionId && e.data.sessionId !== sessionId); // a subagent's events are not this chat's steps
    let at = -1;
    for (let i = events.length - 1; i >= 0 && at < 0; i--) {
      const e = events[i];
      if (!e || e.kind !== 'user' || other(e)) continue;
      const row = live
        ? { role: 'user', value: e.data && e.data.text, attachments: (e.data && e.data.attachments) || [] }
        : { role: 'user', value: e.text, attachments: Array.isArray(e.images) ? e.images : [] };
      if (isPrompt(row)) at = i;
    }
    if (at < 0) return null;
    const raws = new Map();
    let step = null,
      tools = 0,
      talking = false; // the AI's own text came after the newest step: it is on screen, so no live line
    for (let i = at + 1; i < events.length; i++) {
      const e = events[i];
      if (!e || other(e)) continue;
      if (live) {
        const u = (e.kind === 'update' && e.data && e.data.update) || null;
        if (!u) continue;
        if (u.sessionUpdate === 'agent_message_chunk') talking = true;
        else if (u.sessionUpdate === 'agent_thought_chunk') {
          step = { kind: 'thinking' };
          talking = false;
        } else if (u.sessionUpdate === 'tool_call' || u.sessionUpdate === 'tool_call_update') {
          const id = u.toolCallId || 'call-' + i,
            old = raws.get(id);
          raws.set(id, Object.assign({}, old, u));
          if (!old) tools++;
          if (!old) talking = false;
          if (!old || (step && step.id === id))
            step = Object.assign(stepOf({ role: 'tool', raw: raws.get(id) }), { id });
        }
      } else if (e.kind === 'assistant') talking = true;
      else if (e.kind === 'tool') {
        talking = false;
        tools++;
        step = stepOf({ role: 'tool', label: e.label, call: { name: e.label, input: parseJSON(e.text) } });
      } else if (e.kind === 'thinking') {
        step = { kind: 'thinking' };
        talking = false;
      }
    }
    if (!step) step = { kind: 'thinking' };
    delete step.id;
    return { step, n: tools + (step.kind === 'thinking' ? 1 : 0), since: timeMs(events[at].time), talking };
  }

  function project(rows, view, opts) {
    opts = opts || {};
    rows = Array.isArray(rows) ? rows : [];
    if (view === 'prompts') return promptsOf(rows, opts);
    const cap = opts.cap > 0 ? opts.cap : CAP;
    const tailRow = runningPlan(rows);
    let units = split(rows.filter((r) => r !== tailRow));
    if (units.length && !units[0].prompt && opts.earlier) units[0].earlier = true;
    units = units.map((u, index) => {
      const out = { key: u.key, prompt: u.prompt, earlier: u.earlier, body: chatOf(u).body };
      const newest = index === units.length - 1 && !!opts.working;
      if (!out.body.length)
        out.body = [newest ? { line: 'working', text: 'Working…' } : { line: 'none', text: 'No reply' }];
      /* the live line takes the place of the newest run of steps (or comes last): the final reply replaces it when the turn ends */
      if (newest && opts.live && !opts.live.talking) {
        const item = { line: 'working', text: 'Working…', live: opts.live };
        out.body = out.body.filter((b) => b.line !== 'working');
        if (out.body.length && out.body[out.body.length - 1].fold) out.body[out.body.length - 1] = item;
        else out.body.push(item);
      }
      return out;
    });
    /* Cap after projecting, never dropping the newest group or its prompt: older groups go first. */
    let total = units.reduce((n, u) => n + size(u), 0),
      dropped = 0;
    while (total > cap && units.length > 1) {
      total -= size(units.shift());
      dropped++;
    }
    if (dropped && units.length && !units[0].prompt) units[0].earlier = true;
    const flat = [];
    for (const u of units) {
      if (u.prompt) flat.push(u.prompt);
      for (const b of u.body) if (b.row) flat.push(b.row);
    }
    if (tailRow) flat.push(tailRow);
    return { view, units, flat, tail: tailRow, dropped };
  }

  const plural = (n, one, many) => n + ' ' + (n === 1 ? one : many || one + 's');
  /* "Show steps (5 tool calls, 1 failed, thinking)": only the parts that exist */
  function stepsLabel(c) {
    const parts = [];
    if (c.messages) parts.push(plural(c.messages, 'message'));
    if (c.tools) parts.push(plural(c.tools, 'tool call'));
    if (c.failed) parts.push(c.failed + ' failed');
    if (c.thinking) parts.push('thinking');
    return (c.partial ? 'partial: ' : '') + (parts.join(', ') || 'steps');
  }

  /* ---- the choice per chat: localStorage under the chat's aliasKey, least recently used 500 kept ---- */
  const STORE_KEY = 'studio-chat-views',
    STORE_CAP = 500;
  const usable = (v) => VIEWS.includes(v) && AVAILABLE[v];
  function viewStore(storage, fallback) {
    const dflt = () => (typeof fallback === 'function' ? fallback() : fallback);
    let data = null;
    const load = () => {
      if (data) return data;
      try {
        const parsed = JSON.parse(storage.getItem(STORE_KEY));
        data = parsed && typeof parsed === 'object' && !Array.isArray(parsed) ? parsed : {};
        for (const k of Object.keys(data)) if (data[k] === 'outcomes') data[k] = 'chat'; // the Outcomes view is gone: Chat is its successor
      } catch {
        data = {};
      }
      return data;
    };
    const save = () => {
      try {
        storage.setItem(STORE_KEY, JSON.stringify(data));
      } catch {}
    };
    const put = (key, view) => {
      load();
      delete data[key]; // re-inserting moves it to the newest end
      data[key] = view;
      const keys = Object.keys(data);
      for (const k of keys.slice(0, Math.max(0, keys.length - STORE_CAP))) delete data[k];
      save();
    };
    return {
      get(key) {
        const v = key ? load()[key] : null;
        if (usable(v)) return v;
        const d = dflt();
        return DEFAULTABLE.includes(d) ? d : DEFAULT_VIEW; // the Settings default: never Prompts
      },
      has: (key) => !!key && usable(load()[key]),
      set(key, view) {
        if (key && usable(view)) put(key, view);
      },
      /* A new chat's choice moves to the real key when the chat gets one (first send). */
      adopt(from, to) {
        load();
        if (from && to && from !== to && usable(data[from])) {
          const v = data[from];
          delete data[from];
          put(to, v);
        }
      },
    };
  }

  const api = {
    VIEWS,
    LABELS,
    AVAILABLE,
    DEFAULTABLE,
    DEFAULT_VIEW,
    CAP,
    STORE_KEY,
    STORE_CAP,
    isPrompt,
    isInterrupt,
    promptKey,
    runningPlan,
    project,
    stepsLabel,
    promptMatches,
    promptText: userText,
    liveStatus,
    timeMs,
    clock,
    viewStore,
  };
  root.ChatViews = api;
  if (typeof module === 'object' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
